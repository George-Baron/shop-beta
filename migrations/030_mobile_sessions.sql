-- Mobile app sign-in (VELTO-MART native apps). Separate from the website's cookie sessions: those keep working unchanged.
-- Only SHA-256 hashes of tokens are stored, never the tokens themselves.

CREATE TABLE mobile_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL,                       -- random id the app makes once per install
  device_name TEXT NOT NULL DEFAULT '', platform TEXT NOT NULL DEFAULT '', app_version TEXT NOT NULL DEFAULT '',
  access_hash TEXT NOT NULL, access_expires BIGINT NOT NULL,                 -- short-lived (15 minutes)
  refresh_hash TEXT NOT NULL, refresh_expires BIGINT NOT NULL,               -- rotated on every use
  prev_refresh_hash TEXT, rotated_at BIGINT,                                 -- the one before: replaying it later means a token was copied
  created BIGINT NOT NULL, last_used BIGINT NOT NULL, ip TEXT NOT NULL DEFAULT '',
  revoked_at BIGINT, revoke_reason TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX idx_mobile_sessions_access ON mobile_sessions(access_hash);
CREATE UNIQUE INDEX idx_mobile_sessions_refresh ON mobile_sessions(refresh_hash);
CREATE INDEX idx_mobile_sessions_prev ON mobile_sessions(prev_refresh_hash) WHERE prev_refresh_hash IS NOT NULL;
CREATE INDEX idx_mobile_sessions_user ON mobile_sessions(user_id) WHERE revoked_at IS NULL;

-- A customer's request to delete their account. The account is switched off at once; personal details are removed after the waiting period.
CREATE TABLE account_deletions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','done','cancelled')),
  requested_at BIGINT NOT NULL, scheduled_for BIGINT NOT NULL, done_at BIGINT, source TEXT NOT NULL DEFAULT 'mobile'
);
CREATE UNIQUE INDEX idx_account_deletions_open ON account_deletions(user_id) WHERE status = 'pending';
CREATE INDEX idx_account_deletions_due ON account_deletions(scheduled_for) WHERE status = 'pending';

ALTER TABLE mobile_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_deletions ENABLE ROW LEVEL SECURITY;
