-- AI Operations: knowledge records, supplier quotation requests, stock transfer requests.
-- None of these tables holds stock, prices or money: transfers are REQUESTS that a person carries out in the wholesale module,
-- RFQs are messages, and knowledge is notes with an expiry.
CREATE SEQUENCE IF NOT EXISTS ops_rfq_seq;
CREATE SEQUENCE IF NOT EXISTS ops_transfer_seq;

CREATE TABLE IF NOT EXISTS ops_knowledge (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL CHECK (category IN ('procedure','policy','handling','contract','supplier_note','delivery_note','exception','other')),
  title TEXT NOT NULL, body TEXT NOT NULL,
  subject_type TEXT NOT NULL DEFAULT '' CHECK (subject_type IN ('','product','vendor','provider','warehouse')),
  subject_ref TEXT NOT NULL DEFAULT '',
  valid_until BIGINT,                                   -- a time-sensitive fact carries an end date; after it the AI treats it as out of date
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
  created_by TEXT NOT NULL DEFAULT '', updated_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_knowledge_subject ON ops_knowledge (subject_type, subject_ref) WHERE status='active';

CREATE TABLE IF NOT EXISTS ops_rfqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('RFQ-' || lpad(nextval('ops_rfq_seq')::text, 5, '0')),
  request_id BIGINT NOT NULL REFERENCES ops_requests(id) ON DELETE CASCADE,
  vendor_id BIGINT NOT NULL REFERENCES ops_vendors(id) ON DELETE RESTRICT,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','sent','answered','cancelled')),
  subject TEXT NOT NULL, body TEXT NOT NULL, to_email TEXT NOT NULL DEFAULT '',
  sent_at BIGINT, sent_by TEXT NOT NULL DEFAULT '', followups SMALLINT NOT NULL DEFAULT 0, last_followup_at BIGINT, answered_at BIGINT,
  created BIGINT NOT NULL, updated BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_rfqs_live ON ops_rfqs (request_id, vendor_id) WHERE status <> 'cancelled';

CREATE TABLE IF NOT EXISTS ops_stock_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('TRF-' || lpad(nextval('ops_transfer_seq')::text, 5, '0')),
  kind TEXT NOT NULL CHECK (kind IN ('wholesale_to_wholesale','wholesale_to_retail','retail_to_wholesale')),
  product_id BIGINT NOT NULL REFERENCES products(id),
  from_warehouse_id BIGINT REFERENCES wholesale_warehouses(id), to_warehouse_id BIGINT REFERENCES wholesale_warehouses(id),
  qty INTEGER NOT NULL CHECK (qty > 0), reason TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','done','rejected','cancelled')),
  basis JSONB, movement_ref TEXT NOT NULL DEFAULT '',   -- the wholesale stock movement a person made; the AI never moves stock
  requested_by_kind TEXT NOT NULL DEFAULT 'ai' CHECK (requested_by_kind IN ('ai','user')), requested_by TEXT NOT NULL DEFAULT '',
  done_by TEXT NOT NULL DEFAULT '', done_at BIGINT, created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_transfers_open ON ops_stock_transfers (product_id, kind, COALESCE(from_warehouse_id,0), COALESCE(to_warehouse_id,0)) WHERE status='requested';
ALTER TABLE ops_knowledge ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_rfqs ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_stock_transfers ENABLE ROW LEVEL SECURITY;
