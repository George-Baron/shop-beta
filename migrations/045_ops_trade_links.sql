-- AI Operations Manager, phase 5: connects the store's existing import/export shipments (trade_shipments) to the orders and purchase orders they serve.
-- The consignment itself stays in trade_shipments; this table only says which orders ride on it, so order tracking and trade tracking agree.
CREATE TABLE IF NOT EXISTS ops_trade_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id BIGINT NOT NULL REFERENCES trade_shipments(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('order','wholesale','purchase_order')),
  ref_id BIGINT NOT NULL,
  note TEXT NOT NULL DEFAULT '', linked_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL,
  UNIQUE (shipment_id, kind, ref_id)
);
CREATE INDEX IF NOT EXISTS idx_ops_trade_links_ref ON ops_trade_links (kind, ref_id);
ALTER TABLE ops_trade_links ENABLE ROW LEVEL SECURITY;
