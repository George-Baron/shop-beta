-- Product photos named by link in an import file. The shop copies each one into its own storage in the background (never during the upload itself).
CREATE TABLE IF NOT EXISTS catalog_image_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id BIGINT NOT NULL REFERENCES catalog_imports(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  line INT NOT NULL DEFAULT 0,
  pos INT NOT NULL DEFAULT 0,
  url TEXT NOT NULL,
  mode TEXT NOT NULL DEFAULT 'copy' CHECK (mode IN ('copy','link')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','working','done','failed')),
  attempts INT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '',
  result_url TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cij_status ON catalog_image_jobs(status, id);
CREATE INDEX IF NOT EXISTS idx_cij_import ON catalog_image_jobs(import_id, status);
ALTER TABLE catalog_image_jobs ENABLE ROW LEVEL SECURITY;
