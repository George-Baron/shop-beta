-- Wholesale returns: same road as retail returns (request -> review -> owner approval -> refund), kept apart because wholesale quotes are not retail orders.
CREATE TABLE IF NOT EXISTS wholesale_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  quote_id BIGINT NOT NULL REFERENCES wholesale_quotes(id) ON DELETE CASCADE,
  account_id BIGINT NOT NULL REFERENCES wholesale_accounts(id),
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','recommended','awaiting_settlement','settling','settled','rejected','cancelled')),
  reason TEXT NOT NULL DEFAULT '', details TEXT NOT NULL DEFAULT '',
  items JSONB NOT NULL DEFAULT '[]',                       -- [{item_id, product_id, name, qty, unit_price}]
  requested_amount INTEGER NOT NULL DEFAULT 0,             -- Naira: goods value only (delivery and service fees are not refunded by default)
  recommended_amount INTEGER, recommended_note TEXT NOT NULL DEFAULT '', recommended_by BIGINT REFERENCES users(id) ON DELETE SET NULL, recommended_by_name TEXT NOT NULL DEFAULT '', recommended_at BIGINT,
  approved_amount INTEGER, decision_note TEXT NOT NULL DEFAULT '', decided_by BIGINT REFERENCES users(id) ON DELETE SET NULL, decided_by_name TEXT NOT NULL DEFAULT '', decided_at BIGINT,
  approval TEXT NOT NULL DEFAULT '',                       -- owner
  opened_by TEXT NOT NULL DEFAULT 'buyer', opened_by_user BIGINT REFERENCES users(id) ON DELETE SET NULL, opened_by_name TEXT NOT NULL DEFAULT '', open_note TEXT NOT NULL DEFAULT '', past_window SMALLINT NOT NULL DEFAULT 0,
  settle_method TEXT NOT NULL DEFAULT '',                  -- original (Paystack) | manual (bank transfer)
  settle_reference TEXT NOT NULL DEFAULT '', gateway_ref TEXT NOT NULL DEFAULT '', gateway_status TEXT NOT NULL DEFAULT '',
  auto_settle TEXT NOT NULL DEFAULT '', last_error TEXT NOT NULL DEFAULT '', settling_at BIGINT,
  restocked SMALLINT NOT NULL DEFAULT 0, settled_by_name TEXT NOT NULL DEFAULT '', settled_at BIGINT,
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wholesale_returns_status ON wholesale_returns(status, id DESC);
CREATE INDEX IF NOT EXISTS idx_wholesale_returns_quote ON wholesale_returns(quote_id);
CREATE INDEX IF NOT EXISTS idx_wholesale_returns_account ON wholesale_returns(account_id, id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_wholesale_returns_one_open ON wholesale_returns(quote_id) WHERE status IN ('requested','recommended','awaiting_settlement','settling');
ALTER TABLE wholesale_returns ENABLE ROW LEVEL SECURITY;
