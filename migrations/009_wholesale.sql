-- Wholesale buying (our own stock only): buyer applications evaluated by us, wholesale prices with minimum quantities,
-- quote requests, proforma invoices, acceptance, payment BEFORE shipment, then shipment.
CREATE TABLE wholesale_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  vendor_id BIGINT REFERENCES vendors(id),                 -- set when a partner store applies as a buyer too
  business_name TEXT NOT NULL, contact_name TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '',
  reg_no TEXT NOT NULL DEFAULT '', business_type TEXT NOT NULL DEFAULT '', buys TEXT NOT NULL DEFAULT '', est_monthly TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','suspended')),   -- pending = under evaluation
  status_note TEXT NOT NULL DEFAULT '',
  evaluate_until BIGINT NOT NULL,                          -- earliest planned approval date; approving sooner needs an explicit "early" confirmation
  created BIGINT NOT NULL, approved_at BIGINT, approved_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_wholesale_accounts_status ON wholesale_accounts(status, id DESC);

ALTER TABLE products
  ADD COLUMN wholesale_price INTEGER CHECK (wholesale_price IS NULL OR wholesale_price > 0),
  ADD COLUMN wholesale_min_qty INTEGER NOT NULL DEFAULT 1 CHECK (wholesale_min_qty >= 1);

CREATE TABLE wholesale_quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  account_id BIGINT NOT NULL REFERENCES wholesale_accounts(id),
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','quoted','accepted','paid','shipped','delivered','declined','cancelled','expired')),
  buyer_note TEXT NOT NULL DEFAULT '',
  ship_name TEXT NOT NULL DEFAULT '', ship_phone TEXT NOT NULL DEFAULT '', ship_state TEXT NOT NULL DEFAULT '', ship_city TEXT NOT NULL DEFAULT '', ship_address TEXT NOT NULL DEFAULT '',
  goods_total INTEGER NOT NULL DEFAULT 0, logistics_fee INTEGER NOT NULL DEFAULT 0,
  service_pct NUMERIC(5,2) NOT NULL DEFAULT 0, service_fee INTEGER NOT NULL DEFAULT 0, total INTEGER NOT NULL DEFAULT 0,
  valid_until BIGINT, pay_by BIGINT,
  shipment_plan TEXT NOT NULL DEFAULT '', admin_note TEXT NOT NULL DEFAULT '',
  payment_method TEXT NOT NULL DEFAULT '', payment_ref TEXT NOT NULL DEFAULT '', pay_url TEXT NOT NULL DEFAULT '',
  stock_held INTEGER NOT NULL DEFAULT 0,                  -- 1 while the goods are set aside for this buyer
  carrier TEXT NOT NULL DEFAULT '', tracking TEXT NOT NULL DEFAULT '', ship_note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, quoted_at BIGINT, accepted_at BIGINT, paid_at BIGINT, shipped_at BIGINT, delivered_at BIGINT
);
CREATE INDEX idx_wholesale_quotes_account ON wholesale_quotes(account_id, id DESC);
CREATE INDEX idx_wholesale_quotes_status ON wholesale_quotes(status, id DESC);

CREATE TABLE wholesale_quote_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id BIGINT NOT NULL REFERENCES wholesale_quotes(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  name TEXT NOT NULL, qty INTEGER NOT NULL CHECK (qty > 0), list_price INTEGER NOT NULL, unit_price INTEGER NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX idx_wholesale_items_quote ON wholesale_quote_items(quote_id);

CREATE TABLE wholesale_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id BIGINT NOT NULL REFERENCES wholesale_quotes(id) ON DELETE CASCADE,
  status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_events_quote ON wholesale_events(quote_id, id);

ALTER TABLE wholesale_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_quotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_quote_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_events ENABLE ROW LEVEL SECURITY;
