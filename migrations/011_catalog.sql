-- Product details used by bulk import/export, and a history of imports and exports.
ALTER TABLE products ADD COLUMN barcode TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN subcategory TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN cost_price INTEGER NOT NULL DEFAULT 0 CHECK (cost_price >= 0);   -- private: never sent to customers
ALTER TABLE products ADD COLUMN min_stock INTEGER NOT NULL DEFAULT 0 CHECK (min_stock >= 0);     -- reorder alert level ("low stock")
ALTER TABLE products ADD COLUMN unit TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN tax TEXT NOT NULL DEFAULT '';                                     -- a note only, not added to checkout totals
ALTER TABLE products ADD COLUMN weight_kg NUMERIC(8,3) NOT NULL DEFAULT 0 CHECK (weight_kg >= 0);
-- One barcode per seller: our own products share one scope, each partner store has its own.
CREATE UNIQUE INDEX uq_products_barcode ON products (COALESCE(vendor_id, 0), barcode) WHERE barcode <> '';
CREATE INDEX idx_products_sku ON products (COALESCE(vendor_id, 0), lower(sku)) WHERE sku <> '';

CREATE TABLE catalog_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('import', 'export')),
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  vendor_id BIGINT REFERENCES vendors(id) ON DELETE CASCADE,
  mode TEXT NOT NULL DEFAULT '',
  filename TEXT NOT NULL DEFAULT '',
  total INTEGER NOT NULL DEFAULT 0,
  created_n INTEGER NOT NULL DEFAULT 0,
  updated_n INTEGER NOT NULL DEFAULT 0,
  skipped_n INTEGER NOT NULL DEFAULT 0,
  failed_n INTEGER NOT NULL DEFAULT 0,
  created BIGINT NOT NULL
);
CREATE INDEX idx_catalog_log_vendor ON catalog_log (vendor_id, id DESC);
ALTER TABLE catalog_log ENABLE ROW LEVEL SECURITY;
