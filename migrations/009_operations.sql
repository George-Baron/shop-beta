-- Step 8 (operations): a small error log for the admin screen and alerts, and a record of every database backup.
CREATE TABLE error_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint TEXT NOT NULL UNIQUE,         -- the same mistake in the same place counts up instead of adding rows
  source TEXT NOT NULL,                     -- request | job | process | backup
  message TEXT NOT NULL,
  stack TEXT NOT NULL DEFAULT '',
  route TEXT NOT NULL DEFAULT '',
  status INTEGER,
  instance TEXT NOT NULL DEFAULT '',
  count INTEGER NOT NULL DEFAULT 1,
  first_seen BIGINT NOT NULL,
  last_seen BIGINT NOT NULL,
  last_alerted BIGINT,
  resolved_at BIGINT
);
CREATE INDEX idx_error_log_seen ON error_log (last_seen DESC);

CREATE TABLE backups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started BIGINT NOT NULL,
  finished BIGINT,
  state TEXT NOT NULL DEFAULT 'running',    -- running | ok | failed
  kind TEXT NOT NULL DEFAULT 'scheduled',   -- scheduled | manual
  location TEXT NOT NULL DEFAULT '',        -- file name in the private backup storage
  bytes BIGINT NOT NULL DEFAULT 0,
  row_count BIGINT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '',
  instance TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_backups_started ON backups (started DESC);
