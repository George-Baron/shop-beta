-- AI Operations Manager, phase 3: every order is watched from the moment it appears until it is delivered (or ends some other way).
-- ops_order_watch has one row per order or wholesale order: which stage it is in, since when, who has to act next, and what the AI has done about it.
-- ops_order_stage_events is an append-only history of stage changes. Neither table changes an order; the store's own tables stay the source of truth.
CREATE TABLE IF NOT EXISTS ops_order_watch (
  kind TEXT NOT NULL CHECK (kind IN ('order','wholesale')),
  ref_id BIGINT NOT NULL,
  ref TEXT NOT NULL DEFAULT '',
  channel TEXT NOT NULL DEFAULT 'retail',
  stage TEXT NOT NULL,
  owner TEXT NOT NULL DEFAULT '',
  stage_since BIGINT NOT NULL,
  first_seen BIGINT NOT NULL, last_seen BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0, last_action_at BIGINT,
  flags JSONB NOT NULL DEFAULT '{}',
  closed_at BIGINT, outcome TEXT NOT NULL DEFAULT '' CHECK (outcome IN ('','delivered','cancelled','refunded','abandoned','declined','expired')),
  proof TEXT NOT NULL DEFAULT '' CHECK (proof IN ('','verified','pickup','supplier_reported','unproven','not_applicable')),
  PRIMARY KEY (kind, ref_id)
);
CREATE INDEX IF NOT EXISTS idx_ops_order_watch_open ON ops_order_watch (stage) WHERE closed_at IS NULL;

CREATE TABLE IF NOT EXISTS ops_order_stage_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL, ref_id BIGINT NOT NULL,
  from_stage TEXT NOT NULL DEFAULT '', to_stage TEXT NOT NULL,
  detected BIGINT NOT NULL, note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_ops_order_stage_events ON ops_order_stage_events (kind, ref_id, id);

ALTER TABLE ops_order_watch ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_order_stage_events ENABLE ROW LEVEL SECURITY;
