-- Error log for the admin screen and alerts (ported from the rebuild/scale branch).
CREATE TABLE IF NOT EXISTS error_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint TEXT NOT NULL UNIQUE,         -- the same mistake in the same place counts up instead of adding rows
  source TEXT NOT NULL,                     -- request | job | process | backup
  message TEXT NOT NULL,
  stack TEXT NOT NULL DEFAULT '',
  route TEXT NOT NULL DEFAULT '',
  status INTEGER,
  instance TEXT NOT NULL DEFAULT '',
  count INTEGER NOT NULL DEFAULT 1,
  first_seen BIGINT NOT NULL,
  last_seen BIGINT NOT NULL,
  last_alerted BIGINT,
  resolved_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_error_log_seen ON error_log (last_seen DESC);
ALTER TABLE error_log ENABLE ROW LEVEL SECURITY;
