-- Rider management: profiles, consent-based GPS tracking sessions, location history, AI-assisted assignments,
-- rider chat, delivery tracking events, delivery proofs, and an access log for precise rider locations.
--
-- A rider is still a row in users (role = 'rider', that is the sign-in). The riders table holds everything else about them.
-- All times are epoch seconds (BIGINT), like the rest of the schema.
-- RLS is switched on for every table and no policies are granted: nobody can reach these tables through the Supabase public API.
-- The app connects as the database owner and enforces who may see what in code (rider = own data, logistics staff = all, customer = own active delivery only).

CREATE SEQUENCE rider_code_seq START 1;

CREATE TABLE riders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE DEFAULT ('SB-R' || lpad(nextval('rider_code_seq')::text, 3, '0')),
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  vehicle_type TEXT NOT NULL DEFAULT 'motorcycle' CHECK (vehicle_type IN ('bicycle','motorcycle','tricycle','car','van','truck')),
  vehicle_registration TEXT NOT NULL DEFAULT '',
  profile_image TEXT NOT NULL DEFAULT '',
  service_areas TEXT NOT NULL DEFAULT '',                 -- comma-separated areas, e.g. "Ikorodu, Yaba"; empty = anywhere the states in users.coverage allow
  availability_status TEXT NOT NULL DEFAULT 'offline' CHECK (availability_status IN ('offline','available','busy','on_delivery','unavailable')),
  verification_status TEXT NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending','verified','rejected')),
  suspended INTEGER NOT NULL DEFAULT 0 CHECK (suspended IN (0,1)),
  suspended_reason TEXT NOT NULL DEFAULT '',
  maximum_delivery_capacity INTEGER NOT NULL DEFAULT 2 CHECK (maximum_delivery_capacity BETWEEN 1 AND 20),
  location_consent_at BIGINT,                              -- when the rider accepted the location-tracking notice
  last_status_at BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX idx_riders_status ON riders(availability_status) WHERE suspended = 0;

-- Riders that already exist (made in step 6A) get a profile. They were already working, so they start verified and offline.
INSERT INTO riders (user_id, full_name, phone, email, verification_status, created_at, updated_at)
  SELECT id, name, phone, email, 'verified', created, created FROM users WHERE role = 'rider' ORDER BY id;

-- One row per time a rider went online and allowed tracking. At most one can be open per rider.
CREATE TABLE rider_tracking_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
  started_at BIGINT NOT NULL,
  ended_at BIGINT,
  end_reason TEXT NOT NULL DEFAULT '',
  permission_status TEXT NOT NULL DEFAULT 'granted' CHECK (permission_status IN ('granted','denied','unavailable','gps_disabled')),
  tracking_status TEXT NOT NULL DEFAULT 'active' CHECK (tracking_status IN ('active','ended','paused')),
  last_location_at BIGINT,
  client TEXT NOT NULL DEFAULT ''                          -- short description of the device/browser, for support
);
CREATE UNIQUE INDEX uq_tracking_open ON rider_tracking_sessions(rider_id) WHERE ended_at IS NULL;
CREATE INDEX idx_tracking_rider ON rider_tracking_sessions(rider_id, id DESC);

-- Location history. Kept for rider_retention_days (default 30), then deleted by the clean-up job.
CREATE TABLE rider_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
  latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  accuracy DOUBLE PRECISION CHECK (accuracy IS NULL OR accuracy >= 0),   -- metres
  heading DOUBLE PRECISION, speed DOUBLE PRECISION,                       -- degrees, metres per second (when the device knows them)
  location_timestamp BIGINT NOT NULL,                                     -- when the device says the fix was taken
  tracking_session_id BIGINT NOT NULL REFERENCES rider_tracking_sessions(id) ON DELETE CASCADE,
  order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,               -- the delivery in progress, if any
  movement_status TEXT NOT NULL DEFAULT 'unknown' CHECK (movement_status IN ('moving','stationary','unknown')),
  plausible INTEGER NOT NULL DEFAULT 1,                                   -- 0 = failed a server-side sanity check (jump too fast, bad accuracy)
  created_at BIGINT NOT NULL                                              -- when the server received it
);
CREATE INDEX idx_rider_locations_rider ON rider_locations(rider_id, id DESC);
CREATE INDEX idx_rider_locations_created ON rider_locations(created_at);
CREATE INDEX idx_rider_locations_order ON rider_locations(order_id, id DESC) WHERE order_id IS NOT NULL;

-- The newest accepted fix per rider, so the live map and the assignment engine never scan the history.
CREATE TABLE rider_latest_location (
  rider_id BIGINT PRIMARY KEY REFERENCES riders(id) ON DELETE CASCADE,
  latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL, accuracy DOUBLE PRECISION,
  heading DOUBLE PRECISION, speed DOUBLE PRECISION,
  location_timestamp BIGINT NOT NULL, received_at BIGINT NOT NULL,
  tracking_session_id BIGINT NOT NULL REFERENCES rider_tracking_sessions(id) ON DELETE CASCADE,
  order_id BIGINT, movement_status TEXT NOT NULL DEFAULT 'unknown', plausible INTEGER NOT NULL DEFAULT 1
);

-- Offers and deliveries. One live assignment per order, enforced by the database (the unique index below), so two riders can never both hold the same delivery.
CREATE TABLE rider_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT NOT NULL REFERENCES riders(id),
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  assignment_status TEXT NOT NULL DEFAULT 'offered' CHECK (assignment_status IN ('offered','accepted','arrived_pickup','picked_up','in_transit','delivered','rejected','expired','cancelled','failed','reassigned')),
  offered_by TEXT NOT NULL DEFAULT 'ai' CHECK (offered_by IN ('ai','admin','system')),
  assigned_at BIGINT NOT NULL,
  accepted_at BIGINT, rejected_at BIGINT, arrived_pickup_at BIGINT, pickup_at BIGINT, delivered_at BIGINT,
  assignment_timeout_at BIGINT,                                         -- an unanswered offer is released after this time
  reject_reason TEXT NOT NULL DEFAULT '',
  score NUMERIC, score_detail JSONB,                                    -- why this rider was chosen (kept for review)
  pickup_km NUMERIC, delivery_km NUMERIC, eta_min INTEGER,
  closed_reason TEXT NOT NULL DEFAULT '',
  excused INTEGER NOT NULL DEFAULT 0                                    -- 1 = the delay or failure was not the rider's fault (customer unreachable, wrong address, ...): left out of performance scores
);
CREATE UNIQUE INDEX uq_assignment_live ON rider_assignments(order_id) WHERE assignment_status IN ('offered','accepted','arrived_pickup','picked_up','in_transit');
CREATE INDEX idx_assignments_rider ON rider_assignments(rider_id, assignment_status);
CREATE INDEX idx_assignments_order ON rider_assignments(order_id, id DESC);
CREATE INDEX idx_assignments_timeout ON rider_assignments(assignment_timeout_at) WHERE assignment_status = 'offered' AND assignment_timeout_at IS NOT NULL;

-- Chat between a rider and the operations desk (administrators and the AI Operations Manager). One thread per rider.
CREATE TABLE rider_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT NOT NULL REFERENCES riders(id) ON DELETE CASCADE,         -- the thread
  sender_id BIGINT REFERENCES users(id) ON DELETE SET NULL,                 -- empty for the AI and the system
  sender_kind TEXT NOT NULL CHECK (sender_kind IN ('rider','admin','ai','system')),
  recipient_id BIGINT REFERENCES users(id) ON DELETE SET NULL,              -- the rider's user when the message is for the rider; empty when it is for the desk
  order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
  message TEXT NOT NULL CHECK (length(message) BETWEEN 1 AND 2000),
  message_type TEXT NOT NULL DEFAULT 'text',
  attachment_url TEXT NOT NULL DEFAULT '',
  delivered_at BIGINT, read_at BIGINT,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_rider_messages_thread ON rider_messages(rider_id, id DESC);
CREATE INDEX idx_rider_messages_unread_rider ON rider_messages(rider_id) WHERE read_at IS NULL AND sender_kind <> 'rider';
CREATE INDEX idx_rider_messages_unread_desk ON rider_messages(rider_id) WHERE read_at IS NULL AND sender_kind = 'rider';

-- Status changes of a delivery with the rider's position at that moment (a history the admin can review; not a live feed).
CREATE TABLE delivery_tracking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  rider_id BIGINT REFERENCES riders(id) ON DELETE SET NULL,
  latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
  delivery_status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  event_timestamp BIGINT NOT NULL
);
CREATE INDEX idx_delivery_tracking_order ON delivery_tracking(order_id, id);

CREATE TABLE delivery_proofs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
  rider_id BIGINT NOT NULL REFERENCES riders(id),
  otp_verified INTEGER NOT NULL DEFAULT 0,
  proof_image_url TEXT NOT NULL DEFAULT '',
  recipient_confirmation TEXT NOT NULL DEFAULT '',                          -- who received it, as the rider recorded it
  latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
  delivery_timestamp BIGINT NOT NULL
);

-- Customer ratings and complaints about a delivery, recorded by the team (a customer-facing rating form can write here later).
CREATE TABLE rider_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT NOT NULL REFERENCES riders(id) ON DELETE CASCADE,
  order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
  rating INTEGER CHECK (rating BETWEEN 1 AND 5), complaint TEXT NOT NULL DEFAULT '',
  recorded_by TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL
);
CREATE INDEX idx_rider_feedback_rider ON rider_feedback(rider_id, id DESC);
ALTER TABLE rider_feedback ENABLE ROW LEVEL SECURITY;

-- Everything the AI Operations Manager decides or does: rankings, offers, follow-ups, escalations, commands. Nothing happens silently.
CREATE TABLE rider_ops_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT NOT NULL,                                                      -- 'ai', 'system' or an admin's name
  action TEXT NOT NULL,
  order_id BIGINT, rider_id BIGINT,
  detail JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_rider_ops_log_created ON rider_ops_log(created_at DESC);
CREATE INDEX idx_rider_ops_log_order ON rider_ops_log(order_id, id DESC) WHERE order_id IS NOT NULL;

-- Who looked at precise rider locations, and why.
CREATE TABLE location_access_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL, viewer_name TEXT NOT NULL DEFAULT '',
  rider_id BIGINT,                                                          -- empty = the whole map
  purpose TEXT NOT NULL, ip TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL
);
CREATE INDEX idx_location_access_created ON location_access_log(created_at DESC);
CREATE INDEX idx_location_access_rider ON location_access_log(rider_id, id DESC);

-- A short-lived queue the live screens read (server-sent events). Each web instance polls it, so every instance sees every change.
CREATE TABLE rider_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id BIGINT,                                                          -- empty = for the admin screens only
  audience TEXT NOT NULL DEFAULT 'both' CHECK (audience IN ('rider','admin','both')),
  kind TEXT NOT NULL, payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_rider_events_rider ON rider_events(rider_id, id);
CREATE INDEX idx_rider_events_created ON rider_events(created_at);

-- Orders the AI has already warned the desk about (so it does not repeat itself), and the follow-up steps already sent.
CREATE TABLE rider_followups (
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  kind TEXT NOT NULL, created_at BIGINT NOT NULL,
  PRIMARY KEY (order_id, kind)
);

