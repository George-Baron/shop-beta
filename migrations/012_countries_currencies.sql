-- Step 3 of dropshipping: any country, any currency. Prices stay in Naira (the base currency); customers see and pay their own currency.
-- Every statement is safe to run again, and nothing is deleted or rewritten. Seeded rows are placeholders for the admin to review:
-- zones start switched OFF and countries start disabled (except Nigeria), so nothing ships abroad until a person has checked the fees.

CREATE TABLE IF NOT EXISTS shipping_zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT FALSE,                 -- a zone with no rates, or switched off, cannot be shipped to
  extra_per_kg INTEGER NOT NULL DEFAULT 0 CHECK (extra_per_kg >= 0),   -- Naira per extra kg (rounded up) beyond the last weight band
  eta_min INTEGER NOT NULL DEFAULT 5 CHECK (eta_min >= 0), eta_max INTEGER NOT NULL DEFAULT 14 CHECK (eta_max >= eta_min)   -- days from dispatch
);
CREATE TABLE IF NOT EXISTS shipping_rates (               -- delivery fee in Naira by parcel weight: the first band that is big enough
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id BIGINT NOT NULL REFERENCES shipping_zones(id) ON DELETE CASCADE,
  up_to_kg NUMERIC(8,2) NOT NULL CHECK (up_to_kg > 0),
  fee INTEGER NOT NULL CHECK (fee >= 0),
  UNIQUE (zone_id, up_to_kg)
);

CREATE TABLE IF NOT EXISTS countries (
  code CHAR(2) PRIMARY KEY, name TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,                -- customers can only choose enabled countries
  zone_id BIGINT REFERENCES shipping_zones(id) ON DELETE SET NULL,   -- Nigeria uses the state fees in "zones" instead
  currency CHAR(3) NOT NULL DEFAULT 'USD',               -- the currency suggested to customers from this country
  dial_code TEXT NOT NULL DEFAULT '', phone_min SMALLINT NOT NULL DEFAULT 6, phone_max SMALLINT NOT NULL DEFAULT 14,   -- national digits, without the dial code or a leading 0
  postcode_required BOOLEAN NOT NULL DEFAULT FALSE, postcode_regex TEXT NOT NULL DEFAULT '',
  region_label TEXT NOT NULL DEFAULT 'State / region',
  tax_mode TEXT NOT NULL DEFAULT 'none' CHECK (tax_mode IN ('none','added','included')),   -- added = on top of the price; included = already inside the price (shown only)
  tax_pct NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (tax_pct >= 0 AND tax_pct <= 40), tax_label TEXT NOT NULL DEFAULT 'VAT',
  paystack_ok BOOLEAN NOT NULL DEFAULT FALSE,            -- Paystack may be offered here (Nigeria and Africa); other countries pay by international card
  notes TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_countries_enabled ON countries(enabled, name);

CREATE TABLE IF NOT EXISTS currencies (
  code CHAR(3) PRIMARY KEY,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,                -- can only be switched on while a Naira rate exists
  markup_pct NUMERIC(5,2) NOT NULL DEFAULT 2 CHECK (markup_pct >= 0 AND markup_pct <= 20)   -- added to the rate customers are charged at, to cover bank and gateway currency costs
);

-- A product that cannot be sold in a country: banned (never) or restricted (needs a person; not sold online). One target per row.
CREATE TABLE IF NOT EXISTS restricted_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country CHAR(2) NOT NULL REFERENCES countries(code) ON DELETE CASCADE,
  product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
  category_id BIGINT REFERENCES categories(id) ON DELETE CASCADE,
  store TEXT REFERENCES stores(slug) ON DELETE CASCADE,
  kind TEXT NOT NULL DEFAULT 'banned' CHECK (kind IN ('banned','restricted')),
  note TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL DEFAULT 0,
  CHECK ((product_id IS NOT NULL)::int + (category_id IS NOT NULL)::int + (store IS NOT NULL)::int = 1)
);
CREATE INDEX IF NOT EXISTS idx_restricted_country ON restricted_products(country);

-- Rates set by hand stay put: a "locked" rate is never changed by the automatic feed.
ALTER TABLE fx_rates ADD COLUMN IF NOT EXISTS locked BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE fx_rates ADD COLUMN IF NOT EXISTS checked_at BIGINT;

-- What the customer was charged, fixed at checkout so a later rate change can never change an existing order. total/subtotal stay in Naira.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS country CHAR(2) NOT NULL DEFAULT 'NG';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS currency CHAR(3) NOT NULL DEFAULT 'NGN';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS fx_rate NUMERIC(18,8);          -- Naira per 1 unit of currency, including our markup, as charged
ALTER TABLE orders ADD COLUMN IF NOT EXISTS charge_amount BIGINT;           -- minor units of currency (cents, kobo) sent to the payment gateway
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax INTEGER NOT NULL DEFAULT 0; -- Naira of tax added on top (already inside total)
ALTER TABLE orders ADD COLUMN IF NOT EXISTS postcode TEXT NOT NULL DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS gateway TEXT NOT NULL DEFAULT 'paystack';   -- which gateway takes an online payment: paystack | stripe
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pay_session TEXT NOT NULL DEFAULT '';       -- the gateway's own session id (Stripe Checkout Session)
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_label TEXT NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_orders_country ON orders(country) WHERE country <> 'NG';

