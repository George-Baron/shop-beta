-- Step 4 of dropshipping: the order flow. One customer order can mix our own stock, partner-store items and dropship items.
-- Each dropship item gets its own tracked line (dropship_lines) with its own status, supplier order number and tracking.
-- Safe to run again. Nothing is deleted or rewritten.

-- Counts kept on the order so the existing status screens and rider queues can tell a dropship-only order from the rest without extra queries.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS ds_lines INTEGER NOT NULL DEFAULT 0;   -- items that a supplier ships
ALTER TABLE orders ADD COLUMN IF NOT EXISTS own_lines INTEGER NOT NULL DEFAULT 0;  -- items we or a partner store ship (0 on orders from before this step)
ALTER TABLE orders ADD COLUMN IF NOT EXISTS ds_open INTEGER NOT NULL DEFAULT 0;    -- supplier items that are not finished yet

-- A purchase order: what we send a supplier to buy the items of ONE customer order and ship them straight to that customer.
CREATE TABLE IF NOT EXISTS supplier_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL DEFAULT '',
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','sent','cancelled')),
  currency CHAR(3) NOT NULL, total_cost NUMERIC(14,2) NOT NULL DEFAULT 0,   -- what we owe the supplier for these items, in the supplier's currency
  body TEXT NOT NULL DEFAULT '',                                            -- the text of the order as it was generated (also the WhatsApp text)
  sent_via TEXT NOT NULL DEFAULT '' CHECK (sent_via IN ('','email','whatsapp','manual')),
  created BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT '', sent_at BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_supplier_orders_ref ON supplier_orders(ref) WHERE ref <> '';
CREATE INDEX IF NOT EXISTS idx_supplier_orders_order ON supplier_orders(order_id);
CREATE INDEX IF NOT EXISTS idx_supplier_orders_supplier ON supplier_orders(supplier_id, id DESC);

-- One tracked line per dropship item on an order. Cost columns are internal: customers never receive this table.
CREATE TABLE IF NOT EXISTS dropship_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id BIGINT NOT NULL UNIQUE REFERENCES order_items(id) ON DELETE CASCADE,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL, supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  po_id BIGINT REFERENCES supplier_orders(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending_payment' CHECK (status IN ('pending_payment','paid','sent','confirmed','shipped','in_transit','customs','delivered','issue','cancelled','refunded','returned')),
  qty INTEGER NOT NULL CHECK (qty > 0), sell_price INTEGER NOT NULL,                    -- Naira per unit the customer paid: fixed at checkout
  unit_cost NUMERIC(14,2) NOT NULL DEFAULT 0, ship_cost NUMERIC(14,2) NOT NULL DEFAULT 0, cost_currency CHAR(3) NOT NULL DEFAULT 'NGN', cost_ngn INTEGER,   -- supplier cost when ordered (cost_ngn only if a rate existed)
  supplier_sku TEXT NOT NULL DEFAULT '',
  supplier_order_no TEXT NOT NULL DEFAULT '', carrier TEXT NOT NULL DEFAULT '', tracking_no TEXT NOT NULL DEFAULT '', tracking_url TEXT NOT NULL DEFAULT '',
  issue_kind TEXT NOT NULL DEFAULT '' CHECK (issue_kind IN ('','out_of_stock','supplier_cancelled','price_changed','lost','damaged','other')),
  issue_note TEXT NOT NULL DEFAULT '',
  alt_product_id BIGINT,                                                                 -- an alternative offered to the customer
  customer_choice TEXT NOT NULL DEFAULT '' CHECK (customer_choice IN ('','refund','alternative')),
  refund_due INTEGER NOT NULL DEFAULT 0,                                                 -- Naira to give back for this item (price x qty), until the refund is recorded
  refund_reference TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL, paid_at BIGINT, sent_at BIGINT, shipped_at BIGINT, delivered_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_dropship_lines_order ON dropship_lines(order_id);
CREATE INDEX IF NOT EXISTS idx_dropship_lines_status ON dropship_lines(status, supplier_id);
CREATE INDEX IF NOT EXISTS idx_dropship_lines_po ON dropship_lines(po_id) WHERE po_id IS NOT NULL;

-- Every status change, who made it, and an optional key that makes a repeated request do nothing the second time.
CREATE TABLE IF NOT EXISTS dropship_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL REFERENCES dropship_lines(id) ON DELETE CASCADE,
  from_status TEXT NOT NULL DEFAULT '', to_status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
  actor TEXT NOT NULL DEFAULT '', event_key TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_dropship_events_line ON dropship_events(line_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_dropship_events_key ON dropship_events(line_id, event_key) WHERE event_key <> '';

-- Emails can carry one file (the purchase order PDF), stored as base64 in the outbox until the worker sends it.
ALTER TABLE outbox ADD COLUMN IF NOT EXISTS attachment TEXT NOT NULL DEFAULT '';

ALTER TABLE supplier_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE dropship_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE dropship_events ENABLE ROW LEVEL SECURITY;
