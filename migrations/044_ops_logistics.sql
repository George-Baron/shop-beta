-- AI Operations Manager, phase 4: delivery providers, recorded rates, shipments and their tracking events.
-- Nothing here is invented: a rate exists only because a person recorded it from a real quotation or contract, a tracking reference is only what the courier gave,
-- and a tracking event is only what a person (or, later, a verified courier feed) reported. No courier API is connected yet.
CREATE TABLE IF NOT EXISTS ops_providers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'courier' CHECK (kind IN ('courier','third_party','freight','cargo','independent_rider')),
  status TEXT NOT NULL DEFAULT 'under_review' CHECK (status IN ('approved','under_review','suspended')),
  connection TEXT NOT NULL DEFAULT 'manual' CHECK (connection IN ('manual','api_connected')),
  coverage TEXT NOT NULL DEFAULT '', contact TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ops_rate_cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id BIGINT NOT NULL REFERENCES ops_providers(id),
  service TEXT NOT NULL DEFAULT 'standard',
  destination TEXT NOT NULL DEFAULT '*',               -- a Nigerian state, a 2-letter country code, or * for anywhere the provider serves
  min_kg NUMERIC NOT NULL DEFAULT 0, max_kg NUMERIC,
  price NUMERIC NOT NULL CHECK (price > 0), currency TEXT NOT NULL DEFAULT 'NGN',
  eta_days_min INTEGER, eta_days_max INTEGER,
  insured BOOLEAN NOT NULL DEFAULT FALSE,
  source TEXT NOT NULL CHECK (source IN ('provider_quote','contract','published_rate_card')), source_ref TEXT NOT NULL,
  valid_until BIGINT, recorded_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_rate_provider ON ops_rate_cards (provider_id);
CREATE SEQUENCE IF NOT EXISTS ops_shipment_seq;
CREATE TABLE IF NOT EXISTS ops_shipments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  order_kind TEXT NOT NULL DEFAULT 'order' CHECK (order_kind IN ('order','wholesale')), order_id BIGINT NOT NULL,
  provider_id BIGINT NOT NULL REFERENCES ops_providers(id), rate_id BIGINT REFERENCES ops_rate_cards(id),
  service TEXT NOT NULL DEFAULT '', tracking_ref TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'booking_requested' CHECK (status IN ('booking_requested','booked','collected','in_transit','out_for_delivery','delivered','delivered_claimed','failed','returned','cancelled')),
  cost NUMERIC NOT NULL DEFAULT 0, currency TEXT NOT NULL DEFAULT 'NGN', weight_kg NUMERIC,
  eta BIGINT, attempts INTEGER NOT NULL DEFAULT 0,
  approval_id BIGINT, requested_by TEXT NOT NULL DEFAULT '',
  pod_kind TEXT NOT NULL DEFAULT '' CHECK (pod_kind IN ('','courier_confirmation','otp','signature','photo','customer_confirmation')), pod_ref TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL, last_event_at BIGINT, closed_at BIGINT
);
-- one live shipment per order: a second booking for the same order cannot be created while the first is open
CREATE UNIQUE INDEX IF NOT EXISTS uq_ops_shipment_live ON ops_shipments (order_kind, order_id) WHERE status NOT IN ('delivered','delivered_claimed','failed','returned','cancelled');
CREATE INDEX IF NOT EXISTS idx_ops_shipments_open ON ops_shipments (status) WHERE closed_at IS NULL;
CREATE TABLE IF NOT EXISTS ops_shipment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id BIGINT NOT NULL REFERENCES ops_shipments(id),
  status TEXT NOT NULL, location TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '',
  occurred_at BIGINT NOT NULL, source TEXT NOT NULL CHECK (source IN ('staff','courier_feed')), recorded_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_ship_events ON ops_shipment_events (shipment_id, id);
ALTER TABLE ops_providers ENABLE ROW LEVEL SECURITY; ALTER TABLE ops_rate_cards ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_shipments ENABLE ROW LEVEL SECURITY; ALTER TABLE ops_shipment_events ENABLE ROW LEVEL SECURITY;
