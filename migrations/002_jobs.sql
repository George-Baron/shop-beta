-- Background job queue (no Redis needed): rows in Postgres, claimed with FOR UPDATE SKIP LOCKED so many workers never take the same job.
CREATE TABLE jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}',
  state TEXT NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','running','done','failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 6,
  run_at BIGINT NOT NULL,
  locked_until BIGINT,
  last_error TEXT,
  key TEXT UNIQUE,            -- optional de-duplication key: the same key can only be queued once
  created BIGINT NOT NULL,
  finished BIGINT
);
CREATE INDEX idx_jobs_ready ON jobs(run_at) WHERE state IN ('queued','running');
CREATE INDEX idx_jobs_failed ON jobs(finished DESC) WHERE state = 'failed';
CREATE INDEX idx_jobs_done ON jobs(finished) WHERE state = 'done';
ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;
