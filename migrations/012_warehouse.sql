-- Wholesale warehouse foundation (Phase 1).
-- Wholesale stock is now SEPARATE from retail stock: products.stock belongs to the retail store only.
-- Every change to wholesale stock is a row in wholesale_stock_movements, written in the same transaction as the balance change.

CREATE TABLE wholesale_warehouses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  address TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '',
  manager_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created BIGINT NOT NULL
);

CREATE TABLE wholesale_storage_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id BIGINT NOT NULL REFERENCES wholesale_warehouses(id),
  code TEXT NOT NULL,                                       -- e.g. A-03-2
  zone TEXT NOT NULL DEFAULT '', shelf TEXT NOT NULL DEFAULT '', bin TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (warehouse_id, code)
);

-- One row per product per warehouse. on_hand = physical sellable stock; available = on_hand - reserved (never stored, so it cannot drift).
CREATE TABLE wholesale_stock_balances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  warehouse_id BIGINT NOT NULL REFERENCES wholesale_warehouses(id),
  location_id BIGINT REFERENCES wholesale_storage_locations(id) ON DELETE SET NULL,
  on_hand INTEGER NOT NULL DEFAULT 0 CHECK (on_hand >= 0),
  reserved INTEGER NOT NULL DEFAULT 0 CHECK (reserved >= 0),
  picked INTEGER NOT NULL DEFAULT 0 CHECK (picked >= 0),
  opening_qty INTEGER NOT NULL DEFAULT 0, received_qty INTEGER NOT NULL DEFAULT 0, dispatched_qty INTEGER NOT NULL DEFAULT 0,
  damaged_qty INTEGER NOT NULL DEFAULT 0, expired_qty INTEGER NOT NULL DEFAULT 0, returned_qty INTEGER NOT NULL DEFAULT 0, adjustment_qty INTEGER NOT NULL DEFAULT 0,
  reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  updated BIGINT NOT NULL,
  UNIQUE (product_id, warehouse_id),
  CHECK (reserved <= on_hand)                               -- reservations can never exceed what is physically there: no overselling
);
CREATE INDEX idx_wholesale_balances_warehouse ON wholesale_stock_balances(warehouse_id);

CREATE TABLE wholesale_stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,                                 -- MV-2026-000001
  product_id BIGINT NOT NULL REFERENCES products(id),
  warehouse_id BIGINT NOT NULL REFERENCES wholesale_warehouses(id),
  type TEXT NOT NULL CHECK (type IN ('opening','receipt','adjustment','damaged','expired','return','transfer_in','transfer_out','reserve','release','dispatch','migration')),
  qty INTEGER NOT NULL CHECK (qty > 0),                     -- always positive; the effect is in the two delta columns
  delta_on_hand INTEGER NOT NULL DEFAULT 0, delta_reserved INTEGER NOT NULL DEFAULT 0,
  prev_on_hand INTEGER NOT NULL, new_on_hand INTEGER NOT NULL, prev_reserved INTEGER NOT NULL, new_reserved INTEGER NOT NULL,
  related_type TEXT NOT NULL DEFAULT '', related_ref TEXT NOT NULL DEFAULT '',   -- e.g. 'quote' / 'WQ-ABC123', 'receipt' / 'GRN-2026-000004'
  reason TEXT NOT NULL DEFAULT '',
  idempotency_key TEXT UNIQUE,                              -- a retried request with the same key is recognised and not applied twice
  by TEXT NOT NULL DEFAULT '', user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_movements_product ON wholesale_stock_movements(product_id, id DESC);
CREATE INDEX idx_wholesale_movements_related ON wholesale_stock_movements(related_type, related_ref);

CREATE TABLE wholesale_stock_reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id BIGINT NOT NULL REFERENCES wholesale_quotes(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  warehouse_id BIGINT NOT NULL REFERENCES wholesale_warehouses(id),
  qty INTEGER NOT NULL CHECK (qty > 0),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','released','consumed')),
  created BIGINT NOT NULL, closed BIGINT
);
CREATE UNIQUE INDEX uq_wholesale_reservation_active ON wholesale_stock_reservations(quote_id, product_id) WHERE status = 'active';
CREATE INDEX idx_wholesale_reservations_quote ON wholesale_stock_reservations(quote_id);

-- Gap-free-per-year, never-reused document numbers (MV-, GRN-, later INV-, ORDER-, RFQ-), allocated atomically.
CREATE TABLE wholesale_document_sequences (
  kind TEXT NOT NULL, year INTEGER NOT NULL, last_value INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (kind, year)
);

CREATE TABLE wholesale_activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, actor TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL, entity TEXT NOT NULL DEFAULT '', entity_ref TEXT NOT NULL DEFAULT '', detail TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_activity_created ON wholesale_activity_logs(id DESC);
CREATE INDEX idx_wholesale_activity_entity ON wholesale_activity_logs(entity, entity_ref);

-- Warehouse staff roles. The shop's administrator (users.role = 'admin') is the Super Administrator and needs no row here.
CREATE TABLE wholesale_user_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('warehouse_manager','sales_officer','inventory_officer','accounts_officer','dispatch_officer')),
  active INTEGER NOT NULL DEFAULT 1,
  created BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT '',
  UNIQUE (user_id, role)
);
CREATE INDEX idx_wholesale_roles_user ON wholesale_user_roles(user_id) WHERE active = 1;

-- Every wholesale price change is recorded (who, old, new).
CREATE TABLE wholesale_price_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  old_price INTEGER, new_price INTEGER, old_min_qty INTEGER, new_min_qty INTEGER,
  by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_price_history_product ON wholesale_price_history(product_id, id DESC);

