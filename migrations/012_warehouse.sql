-- ---- move goods already set aside for accepted/paid quotes out of the retail count into the wholesale warehouse ----
-- The old code took these goods out of products.stock when the buyer approved. Retail stays as it is (already reduced);
-- the same quantity now appears as wholesale on-hand AND reserved, so nothing is counted twice and nothing is lost.
INSERT INTO wholesale_stock_balances (product_id, warehouse_id, on_hand, reserved, received_qty, updated)
SELECT i.product_id, (SELECT id FROM wholesale_warehouses WHERE code='MAIN'), SUM(i.qty), SUM(i.qty), SUM(i.qty), EXTRACT(EPOCH FROM now())::BIGINT
FROM wholesale_quote_items i JOIN wholesale_quotes q ON q.id = i.quote_id
WHERE q.stock_held = 1 AND q.status IN ('accepted','paid')
GROUP BY i.product_id;

INSERT INTO wholesale_stock_reservations (quote_id, product_id, warehouse_id, qty, status, created)
SELECT i.quote_id, i.product_id, (SELECT id FROM wholesale_warehouses WHERE code='MAIN'), i.qty, 'active', EXTRACT(EPOCH FROM now())::BIGINT
FROM wholesale_quote_items i JOIN wholesale_quotes q ON q.id = i.quote_id
WHERE q.stock_held = 1 AND q.status IN ('accepted','paid');

INSERT INTO wholesale_stock_movements (ref, product_id, warehouse_id, type, qty, delta_on_hand, delta_reserved, prev_on_hand, new_on_hand, prev_reserved, new_reserved, related_type, related_ref, reason, by, created)
SELECT 'MV-MIG-' || b.id, b.product_id, b.warehouse_id, 'migration', b.on_hand, b.on_hand, b.reserved, 0, b.on_hand, 0, b.reserved, 'migration', 'PR-012',
       'Goods already set aside for open wholesale quotes moved from the retail count to the wholesale warehouse', 'system', EXTRACT(EPOCH FROM now())::BIGINT
FROM wholesale_stock_balances b;

-- Quotes already shipped or delivered no longer hold anything.
UPDATE wholesale_quotes SET stock_held = 0 WHERE status IN ('shipped','delivered');

