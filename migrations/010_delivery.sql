-- 6A: delivery mapping, riders, legs per partner, timers, handover code, rider tracking.

-- Partner stores = pickup points. Products with no partner use the default partner.
CREATE TABLE partners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, address TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION, lng DOUBLE PRECISION,
  radius_km DOUBLE PRECISION NOT NULL DEFAULT 0,       -- 0 = use the shop-wide default radius
  is_default INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);
CREATE UNIQUE INDEX uq_partners_default ON partners (is_default) WHERE is_default = 1;
ALTER TABLE products ADD COLUMN partner_id INTEGER REFERENCES partners(id) ON DELETE SET NULL;
CREATE INDEX idx_products_partner ON products(partner_id) WHERE partner_id IS NOT NULL;

-- Riders are users with role 'rider'; they cover a list of states.
CREATE TABLE rider_states (user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, state TEXT NOT NULL, PRIMARY KEY (user_id, state));

ALTER TABLE orders
  ADD COLUMN dest_lat DOUBLE PRECISION, ADD COLUMN dest_lng DOUBLE PRECISION,
  ADD COLUMN dest_landmark TEXT NOT NULL DEFAULT '', ADD COLUMN dest_phone TEXT NOT NULL DEFAULT '',
  ADD COLUMN distance_km DOUBLE PRECISION,
  ADD COLUMN started_at BIGINT,        -- timer start: payment time (online) or phone confirmation (pay on delivery)
  ADD COLUMN promised_at BIGINT, ADD COLUMN eta_min INTEGER,
  ADD COLUMN rider_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN assigned_at BIGINT, ADD COLUMN accepted_at BIGINT, ADD COLUMN picked_up_at BIGINT, ADD COLUMN on_the_way_at BIGINT, ADD COLUMN delivered_at BIGINT,
  ADD COLUMN delivered_lat DOUBLE PRECISION, ADD COLUMN delivered_lng DOUBLE PRECISION,
  ADD COLUMN handover_nonce TEXT NOT NULL DEFAULT '', ADD COLUMN handover_hash TEXT NOT NULL DEFAULT '',   -- the code itself is never stored
  ADD COLUMN handover_attempts INTEGER NOT NULL DEFAULT 0, ADD COLUMN handover_locked INTEGER NOT NULL DEFAULT 0, ADD COLUMN handover_used_at BIGINT,
  ADD COLUMN cash_collected INTEGER;
CREATE INDEX idx_orders_rider ON orders(rider_id, status) WHERE rider_id IS NOT NULL;

-- One pickup per partner on an order.
CREATE TABLE order_legs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  partner_id INTEGER REFERENCES partners(id) ON DELETE SET NULL, partner_name TEXT NOT NULL, partner_address TEXT NOT NULL DEFAULT '', partner_phone TEXT NOT NULL DEFAULT '',
  pickup_lat DOUBLE PRECISION, pickup_lng DOUBLE PRECISION, distance_km DOUBLE PRECISION, picked_up_at BIGINT
);
CREATE INDEX idx_legs_order ON order_legs(order_id);

-- Rider positions during an active delivery. Deleted after 30 days (see lib/jobs.js).
CREATE TABLE rider_points (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  rider_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_points_order ON rider_points(order_id, id DESC);
CREATE INDEX idx_points_created ON rider_points(created);

-- Admin overrides of a locked handover code, with the reason.
CREATE TABLE handover_audit (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE, actor TEXT NOT NULL, action TEXT NOT NULL, reason TEXT NOT NULL, created BIGINT NOT NULL);

-- Cached geocoding and routing answers (so a map provider is never called per page view).
CREATE TABLE geo_cache (key TEXT PRIMARY KEY, value TEXT NOT NULL, created BIGINT NOT NULL);
CREATE INDEX idx_geo_cache_created ON geo_cache(created);

