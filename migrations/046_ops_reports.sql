-- AI Operations Manager, phase 6: stored operations reports. Each report is built from recorded data by code (no model writes the numbers) and kept as it was,
-- so management can look back at what the figures said at the time. One report per kind and period.
CREATE TABLE IF NOT EXISTS ops_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('daily','weekly','monthly')),
  period_start BIGINT NOT NULL, period_end BIGINT NOT NULL,
  title TEXT NOT NULL, headline JSONB NOT NULL DEFAULT '[]', data JSONB NOT NULL DEFAULT '{}',
  generated_by TEXT NOT NULL DEFAULT 'VELTO AI', generated BIGINT NOT NULL,
  UNIQUE (kind, period_start)
);
ALTER TABLE ops_reports ENABLE ROW LEVEL SECURITY;
