-- Phase 2 and 3: employee accounts with roles and permissions, login history, the notification centre, and wholesale requests for quotation (RFQ).

-- Roles hold a list of permissions like "orders:view" and "orders:edit". Employees are users with role 'staff'.
CREATE TABLE staff_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE, description TEXT NOT NULL DEFAULT '',
  perms TEXT NOT NULL DEFAULT '[]',
  builtin INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);
ALTER TABLE users
  ADD COLUMN username CITEXT UNIQUE,
  ADD COLUMN staff_role_id BIGINT REFERENCES staff_roles(id),
  ADD COLUMN staff_perms TEXT,                      -- when set, replaces the role's permissions for this one person
  ADD COLUMN last_login BIGINT;
CREATE INDEX idx_users_staff_role ON users(staff_role_id) WHERE staff_role_id IS NOT NULL;

CREATE TABLE login_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE, who TEXT NOT NULL DEFAULT '',
  ok INTEGER NOT NULL, ip TEXT NOT NULL DEFAULT '', agent TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_login_log_user ON login_log(user_id, id DESC);

-- Notification centre: one row per person per event. Email copies go through the normal mail queue.
CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type TEXT NOT NULL DEFAULT '', title TEXT NOT NULL, body TEXT NOT NULL DEFAULT '', link TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, read_at BIGINT
);
CREATE INDEX idx_notifications_user ON notifications(user_id, id DESC);
CREATE INDEX idx_notifications_unread ON notifications(user_id) WHERE read_at IS NULL;

-- Requests for quotation from approved wholesale buyers.
CREATE TABLE rfqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  account_id BIGINT NOT NULL REFERENCES wholesale_accounts(id),
  company TEXT NOT NULL DEFAULT '', contact_name TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  delivery_location TEXT NOT NULL DEFAULT '', required_date TEXT NOT NULL DEFAULT '', comments TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted','received','review','sourcing','quote_prepared','quote_sent','accepted','rejected','converted','completed')),
  assigned_to BIGINT REFERENCES users(id), assigned_at BIGINT,
  quote_goods INTEGER NOT NULL DEFAULT 0, quote_logistics INTEGER NOT NULL DEFAULT 0, quote_service_pct NUMERIC(5,2) NOT NULL DEFAULT 0, quote_service INTEGER NOT NULL DEFAULT 0, quote_total INTEGER NOT NULL DEFAULT 0,
  quote_valid_until BIGINT, quote_note TEXT NOT NULL DEFAULT '', shipment_plan TEXT NOT NULL DEFAULT '', reject_reason TEXT NOT NULL DEFAULT '',
  sales_ref TEXT NOT NULL DEFAULT '',                      -- the wholesale order (WQ-...) made from an accepted quotation
  created BIGINT NOT NULL, submitted_at BIGINT, quoted_at BIGINT, closed_at BIGINT, updated BIGINT NOT NULL
);
CREATE INDEX idx_rfqs_account ON rfqs(account_id, id DESC);
CREATE INDEX idx_rfqs_status ON rfqs(status, id DESC);
CREATE INDEX idx_rfqs_assigned ON rfqs(assigned_to, status);

CREATE TABLE rfq_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id) ON DELETE CASCADE,
  name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', barcode TEXT NOT NULL DEFAULT '', qty INTEGER NOT NULL CHECK (qty > 0),
  brand TEXT NOT NULL DEFAULT '', packaging TEXT NOT NULL DEFAULT '', target_price INTEGER CHECK (target_price IS NULL OR target_price >= 0),
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,          -- set by our team when the item is matched to a catalogue product
  unit_price INTEGER CHECK (unit_price IS NULL OR unit_price >= 0), item_note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_rfq_items_rfq ON rfq_items(rfq_id);

CREATE TABLE rfq_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id) ON DELETE CASCADE,
  name TEXT NOT NULL, stored TEXT NOT NULL, size INTEGER NOT NULL DEFAULT 0, mime TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_rfq_files_rfq ON rfq_files(rfq_id);

CREATE TABLE rfq_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rfq_id BIGINT NOT NULL REFERENCES rfqs(id) ON DELETE CASCADE,
  status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_rfq_events_rfq ON rfq_events(rfq_id, id);

