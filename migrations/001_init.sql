-- Shop-Beta schema, PostgreSQL. Ported from the SQLite version.
-- Flags stay as 0/1 integers and money stays in whole Naira so the front end does not change.
-- Times are unix seconds (BIGINT). Emails are stored lower case and made unique case-insensitively.

CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');

CREATE TABLE stores (
  slug TEXT PRIMARY KEY, name TEXT NOT NULL, tab_label TEXT NOT NULL, icon TEXT NOT NULL DEFAULT '🛍',
  tagline TEXT NOT NULL DEFAULT '', hero_title TEXT NOT NULL DEFAULT '', hero_sub TEXT NOT NULL DEFAULT '', hero_cta TEXT NOT NULL DEFAULT 'Shop now',
  promo1_title TEXT NOT NULL DEFAULT '', promo1_sub TEXT NOT NULL DEFAULT '', promo2_title TEXT NOT NULL DEFAULT '', promo2_sub TEXT NOT NULL DEFAULT '',
  banner_title TEXT NOT NULL DEFAULT '', banner_sub TEXT NOT NULL DEFAULT '', sort INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store TEXT NOT NULL REFERENCES stores(slug) ON DELETE CASCADE, slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, icon TEXT NOT NULL DEFAULT '🛍', sort INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_categories_store ON categories(store, sort, id);

CREATE TABLE products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, store TEXT NOT NULL REFERENCES stores(slug),
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  name TEXT NOT NULL, brand TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL, compare_price INTEGER NOT NULL DEFAULT 0, stock INTEGER NOT NULL DEFAULT 0,
  sku TEXT NOT NULL DEFAULT '', emoji TEXT NOT NULL DEFAULT '📦', images TEXT NOT NULL DEFAULT '[]', size_label TEXT NOT NULL DEFAULT 'Size',
  featured INTEGER NOT NULL DEFAULT 0, bestseller INTEGER NOT NULL DEFAULT 0, new_arrival INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1, sold INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);

CREATE TABLE variants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  size TEXT NOT NULL DEFAULT '', color TEXT NOT NULL DEFAULT '', stock INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_variants_product ON variants(product_id);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '',
  password TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'customer', created BIGINT NOT NULL
);
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));

CREATE TABLE sessions (
  id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires);

CREATE TABLE resets (
  token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL
);
CREATE INDEX idx_resets_user ON resets(user_id);
CREATE INDEX idx_resets_expires ON resets(expires);

CREATE TABLE addresses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT 'Home', name TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL, city TEXT NOT NULL DEFAULT '', address TEXT NOT NULL
);
CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE TABLE wishlist (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, product_id)
);
CREATE INDEX idx_wishlist_product ON wishlist(product_id);

CREATE TABLE zones (
  state TEXT PRIMARY KEY, fee INTEGER NOT NULL DEFAULT 0, eta TEXT NOT NULL DEFAULT '', pod INTEGER NOT NULL DEFAULT 1, sort INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE coupons (
  code TEXT PRIMARY KEY, type TEXT NOT NULL DEFAULT 'percent', value INTEGER NOT NULL, min_spend INTEGER NOT NULL DEFAULT 0,
  max_uses INTEGER NOT NULL DEFAULT 0, used INTEGER NOT NULL DEFAULT 0, expires_at TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1,
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE UNIQUE INDEX uq_coupons_code ON coupons (lower(code));

CREATE TABLE orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref TEXT NOT NULL UNIQUE, user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending', payment_method TEXT NOT NULL, payment_status TEXT NOT NULL DEFAULT 'unpaid', paystack_ref TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL, state TEXT NOT NULL, city TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
  delivery TEXT NOT NULL DEFAULT 'standard', delivery_fee INTEGER NOT NULL DEFAULT 0, subtotal INTEGER NOT NULL, discount INTEGER NOT NULL DEFAULT 0,
  coupon TEXT NOT NULL DEFAULT '', total INTEGER NOT NULL, created BIGINT NOT NULL
);

CREATE TABLE order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE, product_id INTEGER NOT NULL, variant_id INTEGER,
  name TEXT NOT NULL, variant_label TEXT NOT NULL DEFAULT '', price INTEGER NOT NULL, qty INTEGER NOT NULL, emoji TEXT NOT NULL DEFAULT '', image TEXT NOT NULL DEFAULT ''
);

CREATE TABLE order_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE, status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);

CREATE TABLE reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE, user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL, rating INTEGER NOT NULL, title TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', approved INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);

CREATE TABLE messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL, subject TEXT NOT NULL DEFAULT '', body TEXT NOT NULL, read INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);

CREATE TABLE newsletter (email TEXT PRIMARY KEY, created BIGINT NOT NULL);
CREATE UNIQUE INDEX uq_newsletter_email ON newsletter (lower(email));

CREATE TABLE abandoned (email TEXT PRIMARY KEY, cart TEXT NOT NULL, created BIGINT NOT NULL, reminded INTEGER NOT NULL DEFAULT 0);

CREATE TABLE outbox (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, to_email TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL, sent INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);
