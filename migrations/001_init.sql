-- Shop-Beta schema for PostgreSQL (Supabase or local). Timestamps are unix seconds (BIGINT) as before.
CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');

CREATE TABLE stores (
  slug TEXT PRIMARY KEY, name TEXT NOT NULL, tab_label TEXT NOT NULL, icon TEXT NOT NULL DEFAULT '🛍',
  tagline TEXT NOT NULL DEFAULT '', hero_title TEXT NOT NULL DEFAULT '', hero_sub TEXT NOT NULL DEFAULT '', hero_cta TEXT NOT NULL DEFAULT 'Shop now',
  promo1_title TEXT NOT NULL DEFAULT '', promo1_sub TEXT NOT NULL DEFAULT '', promo2_title TEXT NOT NULL DEFAULT '', promo2_sub TEXT NOT NULL DEFAULT '',
  banner_title TEXT NOT NULL DEFAULT '', banner_sub TEXT NOT NULL DEFAULT '', sort INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store TEXT NOT NULL REFERENCES stores(slug) ON DELETE CASCADE, slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, icon TEXT NOT NULL DEFAULT '🛍', sort INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_categories_store ON categories(store, sort, id);

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, store TEXT NOT NULL REFERENCES stores(slug),
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  name TEXT NOT NULL, brand TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL CHECK (price >= 0), compare_price INTEGER NOT NULL DEFAULT 0, stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  sku TEXT NOT NULL DEFAULT '', emoji TEXT NOT NULL DEFAULT '📦', images TEXT NOT NULL DEFAULT '[]', size_label TEXT NOT NULL DEFAULT 'Size',
  featured INTEGER NOT NULL DEFAULT 0, bestseller INTEGER NOT NULL DEFAULT 0, new_arrival INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1, sold INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);
-- product listing: department pages, featured, best sellers, newest, price sort, filters
CREATE INDEX idx_products_store_active ON products(store, active, id DESC);
CREATE INDEX idx_products_active_featured ON products(active, featured DESC, id DESC);
CREATE INDEX idx_products_store_sold ON products(store, active, sold DESC, id DESC);
CREATE INDEX idx_products_store_created ON products(store, active, created DESC);
CREATE INDEX idx_products_price ON products(active, price);
CREATE INDEX idx_products_cat ON products(category_id);
-- search: "contains" matching on name, brand, sku and description
CREATE INDEX idx_products_name_trgm ON products USING gin (lower(name) gin_trgm_ops);
CREATE INDEX idx_products_brand_trgm ON products USING gin (lower(brand) gin_trgm_ops);
CREATE INDEX idx_products_sku_trgm ON products USING gin (lower(sku) gin_trgm_ops);
CREATE INDEX idx_products_desc_trgm ON products USING gin (lower(description) gin_trgm_ops);

CREATE TABLE variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  size TEXT NOT NULL DEFAULT '', color TEXT NOT NULL DEFAULT '', stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);
CREATE INDEX idx_variants_product ON variants(product_id);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email CITEXT NOT NULL UNIQUE, phone TEXT NOT NULL DEFAULT '',
  password TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'customer', created BIGINT NOT NULL
);
CREATE INDEX idx_users_role ON users(role);

CREATE TABLE sessions (
  id TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires);

CREATE TABLE resets (
  token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires BIGINT NOT NULL
);
CREATE INDEX idx_resets_user ON resets(user_id);

CREATE TABLE addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT 'Home', name TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL, city TEXT NOT NULL DEFAULT '', address TEXT NOT NULL
);
CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE TABLE wishlist (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, product_id)
);

CREATE TABLE zones (
  state TEXT PRIMARY KEY, fee INTEGER NOT NULL DEFAULT 0, eta TEXT NOT NULL DEFAULT '', pod INTEGER NOT NULL DEFAULT 1, sort INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE coupons (
  code CITEXT PRIMARY KEY, type TEXT NOT NULL DEFAULT 'percent', value INTEGER NOT NULL, min_spend INTEGER NOT NULL DEFAULT 0,
  max_uses INTEGER NOT NULL DEFAULT 0, used INTEGER NOT NULL DEFAULT 0, expires_at TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1,
  created_seq BIGINT GENERATED ALWAYS AS IDENTITY
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref TEXT NOT NULL UNIQUE, user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending', payment_method TEXT NOT NULL, payment_status TEXT NOT NULL DEFAULT 'unpaid', paystack_ref TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT NOT NULL, state TEXT NOT NULL, city TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
  delivery TEXT NOT NULL DEFAULT 'standard', delivery_fee INTEGER NOT NULL DEFAULT 0, subtotal INTEGER NOT NULL, discount INTEGER NOT NULL DEFAULT 0,
  coupon TEXT NOT NULL DEFAULT '', total INTEGER NOT NULL, created BIGINT NOT NULL
);
-- orders by user, by status, by date, by email; plus the unpaid-online-order sweep
CREATE INDEX idx_orders_created ON orders(created DESC);
CREATE INDEX idx_orders_user ON orders(user_id, id DESC);
CREATE INDEX idx_orders_status ON orders(status, id DESC);
CREATE INDEX idx_orders_email ON orders(lower(email));
CREATE INDEX idx_orders_unpaid_online ON orders(created) WHERE payment_method = 'paystack' AND payment_status = 'unpaid' AND status = 'pending';

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE, product_id BIGINT NOT NULL, variant_id BIGINT,
  name TEXT NOT NULL, variant_label TEXT NOT NULL DEFAULT '', price INTEGER NOT NULL, qty INTEGER NOT NULL, emoji TEXT NOT NULL DEFAULT '', image TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_items_order ON order_items(order_id);
CREATE INDEX idx_items_product ON order_items(product_id);

CREATE TABLE order_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE, status TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_events_order ON order_events(order_id, id);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE, user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL, rating INTEGER NOT NULL, title TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', approved INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);
CREATE INDEX idx_reviews_product ON reviews(product_id, approved);
CREATE UNIQUE INDEX uq_reviews_user_product ON reviews(product_id, user_id) WHERE user_id IS NOT NULL;

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL, subject TEXT NOT NULL DEFAULT '', body TEXT NOT NULL, read INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);
CREATE INDEX idx_messages_unread ON messages(read);

CREATE TABLE newsletter (email CITEXT PRIMARY KEY, created BIGINT NOT NULL);
CREATE TABLE abandoned (email CITEXT PRIMARY KEY, cart TEXT NOT NULL, created BIGINT NOT NULL, reminded INTEGER NOT NULL DEFAULT 0);
CREATE INDEX idx_abandoned_created ON abandoned(created);

CREATE TABLE outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, to_email TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL, sent INTEGER NOT NULL DEFAULT 0, created BIGINT NOT NULL
);
CREATE INDEX idx_outbox_created ON outbox(created);

-- Supabase exposes the "public" schema through its Data API. Turn on row-level security with no policies on every table
-- so the public (anon) key can read nothing; the app connects with the database role directly, which is not affected.
DO $$
DECLARE t TEXT;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
