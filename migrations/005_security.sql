-- Step 7: shared rate limits (same limits across all instances), admin activity log, private order link token.
CREATE TABLE rate_limits (key TEXT PRIMARY KEY, n INTEGER NOT NULL, reset_at BIGINT NOT NULL);
CREATE INDEX idx_rate_limits_reset ON rate_limits(reset_at);
CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT, user_name TEXT NOT NULL DEFAULT '', method TEXT NOT NULL, path TEXT NOT NULL, status INTEGER NOT NULL,
  detail TEXT NOT NULL DEFAULT '', ip TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_audit_created ON audit_log(created DESC);
-- A secret link token for each order. With it the customer sees full order details; with only order number + email they see a masked view.
ALTER TABLE orders ADD COLUMN access_token TEXT NOT NULL DEFAULT '';
UPDATE orders SET access_token = md5(random()::text || id::text) || md5(random()::text) WHERE access_token = '';
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
