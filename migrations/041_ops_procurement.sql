-- AI Operations Manager, phase 2: procurement intelligence.
-- Vendors (separate from the dropship supplier portal, but may point to a supplier row), what each vendor told us (quotations), what we need
-- (procurement requests) and what we intend to buy (purchase orders). Nothing here moves money. RLS on, no policies: the app checks access in code.

CREATE SEQUENCE IF NOT EXISTS ops_vendor_seq;
CREATE SEQUENCE IF NOT EXISTS ops_request_seq;
CREATE SEQUENCE IF NOT EXISTS ops_quote_seq;
CREATE SEQUENCE IF NOT EXISTS ops_po_seq;

CREATE TABLE IF NOT EXISTS ops_vendors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('VND-' || lpad(nextval('ops_vendor_seq')::text, 4, '0')),
  supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,        -- the existing dropship supplier, when it is the same business
  name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'distributor' CHECK (kind IN ('local_manufacturer','distributor','wholesaler','authorized_distributor','international_manufacturer','importer','exporter','marketplace','other')),
  country CHAR(2) NOT NULL DEFAULT 'NG' CHECK (country ~ '^[A-Z]{2}$'),
  location TEXT NOT NULL DEFAULT '',
  website TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  registration_no TEXT NOT NULL DEFAULT '',
  currency CHAR(3) NOT NULL DEFAULT 'NGN' CHECK (currency ~ '^[A-Z]{3}$'),
  payment_terms TEXT NOT NULL DEFAULT '', payment_days INTEGER NOT NULL DEFAULT 0 CHECK (payment_days BETWEEN 0 AND 365),
  lead_days INTEGER CHECK (lead_days IS NULL OR lead_days BETWEEN 0 AND 365),
  return_policy TEXT NOT NULL DEFAULT '', warranty TEXT NOT NULL DEFAULT '', certifications TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'under_review' CHECK (status IN ('preferred','approved','conditional','under_review','suspended','rejected')),
  -- what has actually been checked, field by field: { registration: {state:'verified'|'vendor_supplied'|'unverified', by:, at:, note:} ... }
  verification JSONB NOT NULL DEFAULT '{}',
  notes TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_vendors_name ON ops_vendors (lower(name), country);

-- Ratings a person gives (quality, responsiveness). They are inputs: the system never makes them up.
CREATE TABLE IF NOT EXISTS ops_vendor_ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL REFERENCES ops_vendors(id) ON DELETE CASCADE,
  quality SMALLINT CHECK (quality BETWEEN 0 AND 100),
  responsiveness SMALLINT CHECK (responsiveness BETWEEN 0 AND 100),
  note TEXT NOT NULL DEFAULT '',
  rated_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_vendor_ratings ON ops_vendor_ratings(vendor_id, id DESC);

CREATE TABLE IF NOT EXISTS ops_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('REQ-' || lpad(nextval('ops_request_seq')::text, 5, '0')),
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  sku TEXT NOT NULL DEFAULT '', description TEXT NOT NULL,
  qty INTEGER NOT NULL CHECK (qty > 0),
  target_price NUMERIC(14,2) CHECK (target_price IS NULL OR target_price >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  required_by BIGINT,
  destination TEXT NOT NULL DEFAULT 'retail' CHECK (destination IN ('retail','wholesale')),   -- the two stocks are never mixed
  justification TEXT NOT NULL DEFAULT '',
  est_budget NUMERIC(14,2), department TEXT NOT NULL DEFAULT 'Operations',
  priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','ai_stock')),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','quoted','po_drafted','ordered','closed','cancelled')),
  basis JSONB,                                                          -- the numbers the AI used (stock, demand, cover days), so the reason can be checked
  created BIGINT NOT NULL, updated BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_ops_requests_status ON ops_requests(status, id DESC);
-- one open request per product and destination, so the AI does not pile up duplicates
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_requests_open_product ON ops_requests(product_id, destination) WHERE product_id IS NOT NULL AND status IN ('open','quoted','po_drafted');

-- A price a vendor actually gave us (or a catalogue price a person copied in). source says where it came from; the AI never writes a price on its own.
CREATE TABLE IF NOT EXISTS ops_quotations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('QUO-' || lpad(nextval('ops_quote_seq')::text, 5, '0')),
  request_id BIGINT NOT NULL REFERENCES ops_requests(id) ON DELETE CASCADE,
  vendor_id BIGINT NOT NULL REFERENCES ops_vendors(id) ON DELETE RESTRICT,
  unit_price NUMERIC(14,4) NOT NULL CHECK (unit_price >= 0),
  currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  moq INTEGER NOT NULL DEFAULT 1 CHECK (moq >= 1),
  qty_available INTEGER CHECK (qty_available IS NULL OR qty_available >= 0),
  incoterm TEXT NOT NULL DEFAULT 'DAP',
  freight NUMERIC(14,2) NOT NULL DEFAULT 0, insurance NUMERIC(14,2) NOT NULL DEFAULT 0, other_fees NUMERIC(14,2) NOT NULL DEFAULT 0,
  duty_pct NUMERIC(6,2) NOT NULL DEFAULT 0, vat_pct NUMERIC(6,2) NOT NULL DEFAULT 0, clearing_fee NUMERIC(14,2) NOT NULL DEFAULT 0,
  lead_days INTEGER CHECK (lead_days IS NULL OR lead_days BETWEEN 0 AND 365),
  payment_days INTEGER CHECK (payment_days IS NULL OR payment_days BETWEEN 0 AND 365),
  valid_until BIGINT,
  source TEXT NOT NULL CHECK (source IN ('vendor_quote','vendor_catalogue','verbal','manual')),
  source_ref TEXT NOT NULL DEFAULT '',                                   -- the email, invoice or page the price came from
  note TEXT NOT NULL DEFAULT '',
  entered_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_quotations_req ON ops_quotations(request_id, id);

CREATE TABLE IF NOT EXISTS ops_purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('PO-' || lpad(nextval('ops_po_seq')::text, 5, '0')),
  request_id BIGINT REFERENCES ops_requests(id) ON DELETE SET NULL,
  vendor_id BIGINT NOT NULL REFERENCES ops_vendors(id) ON DELETE RESTRICT,
  quotation_id BIGINT REFERENCES ops_quotations(id) ON DELETE SET NULL,
  lines JSONB NOT NULL DEFAULT '[]',                                     -- [{product_id, sku, description, qty, unit_price}]
  currency CHAR(3) NOT NULL,
  subtotal NUMERIC(16,2) NOT NULL DEFAULT 0, discount NUMERIC(16,2) NOT NULL DEFAULT 0, tax NUMERIC(16,2) NOT NULL DEFAULT 0, delivery NUMERIC(16,2) NOT NULL DEFAULT 0,
  total NUMERIC(16,2) NOT NULL DEFAULT 0,
  destination TEXT NOT NULL DEFAULT 'retail' CHECK (destination IN ('retail','wholesale')),
  expected_date BIGINT, payment_terms TEXT NOT NULL DEFAULT '', terms TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending_approval','approved','sent','accepted','dispatched','received','cancelled')),
  approval_id BIGINT REFERENCES ops_approvals(id) ON DELETE SET NULL,
  sent_at BIGINT, sent_by TEXT NOT NULL DEFAULT '', vendor_ref TEXT NOT NULL DEFAULT '',
  created_by_kind TEXT NOT NULL DEFAULT 'ai' CHECK (created_by_kind IN ('ai','user')), created_by TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_po_status ON ops_purchase_orders(status, id DESC);
-- one live PO per request and vendor: asking twice does not make two
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_po_live ON ops_purchase_orders(request_id, vendor_id) WHERE request_id IS NOT NULL AND status NOT IN ('cancelled');

-- What actually arrived. Recorded by a person (the AI cannot confirm goods receipt). Drives a vendor's delivery reliability.
CREATE TABLE IF NOT EXISTS ops_po_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_id BIGINT NOT NULL REFERENCES ops_purchase_orders(id) ON DELETE CASCADE,
  qty_ordered INTEGER NOT NULL, qty_received INTEGER NOT NULL CHECK (qty_received >= 0),
  received_at BIGINT NOT NULL, on_time SMALLINT NOT NULL CHECK (on_time IN (0,1)),
  note TEXT NOT NULL DEFAULT '', received_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);

ALTER TABLE ops_vendors ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_vendor_ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_quotations ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_purchase_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE ops_po_receipts ENABLE ROW LEVEL SECURITY;
