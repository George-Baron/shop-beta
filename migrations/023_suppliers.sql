-- Dropshipping, step 1: suppliers (any country, any currency), their private documents, and a performance ledger.
-- Written to be safe to re-run: every statement is guarded.
CREATE TABLE IF NOT EXISTS suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  country CHAR(2) NOT NULL CHECK (country ~ '^[A-Z]{2}$'),                  -- ISO 3166-1 alpha-2, e.g. CN, NG, GB
  contact_name TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', whatsapp TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),                -- ISO 4217: the currency the supplier invoices us in
  payment_terms TEXT NOT NULL DEFAULT '',                                   -- label shown to staff, e.g. "Net 14"
  payment_days INTEGER NOT NULL DEFAULT 0 CHECK (payment_days >= 0 AND payment_days <= 365),   -- days after we place an order that we must pay (0 = prepaid)
  processing_days INTEGER NOT NULL DEFAULT 3 CHECK (processing_days >= 0 AND processing_days <= 120),   -- average days before they ship
  shipping_methods TEXT NOT NULL DEFAULT '',                                -- comma list of: air, sea, courier, local
  margin_type TEXT CHECK (margin_type IS NULL OR margin_type IN ('percent','fixed')),   -- optional margin rule for this supplier (used in step 2)
  margin_value NUMERIC(12,2) CHECK (margin_value IS NULL OR margin_value >= 0),
  notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused')),
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_suppliers_status ON suppliers(status, name);
CREATE INDEX IF NOT EXISTS idx_suppliers_name_trgm ON suppliers USING gin (lower(name) gin_trgm_ops);

-- Files are kept in a PRIVATE storage bucket; this table only records what each file is.
CREATE TABLE IF NOT EXISTS supplier_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('registration','agreement','other')),
  file_key TEXT NOT NULL, file_name TEXT NOT NULL DEFAULT '', mime TEXT NOT NULL DEFAULT 'application/octet-stream', bytes INTEGER NOT NULL DEFAULT 0,
  created BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_supplier_docs ON supplier_documents(supplier_id, id DESC);

-- One row per thing that happened. Step 4 will write 'order' rows by itself; until then staff can record them.
CREATE TABLE IF NOT EXISTS supplier_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('order','late','cancellation','defect','rating')),
  rating SMALLINT CHECK (rating IS NULL OR (rating >= 1 AND rating <= 5)),
  ref TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT '',
  CHECK ((kind = 'rating') = (rating IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_supplier_events ON supplier_events(supplier_id, id DESC);

ALTER TABLE suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE supplier_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE supplier_events ENABLE ROW LEVEL SECURITY;
