-- VELTO REWARDS: referrals and campaigns. Safe to run again.
CREATE TABLE IF NOT EXISTS loyalty_referrals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_id BIGINT NOT NULL REFERENCES users(id),
  referred_id BIGINT NOT NULL UNIQUE REFERENCES users(id),     -- a person can only ever be referred once
  code TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'registered' CHECK (status IN ('registered','rewarded','rejected')),
  reason TEXT NOT NULL DEFAULT '',
  order_ref TEXT NOT NULL DEFAULT '',
  referrer_points BIGINT NOT NULL DEFAULT 0, referred_points BIGINT NOT NULL DEFAULT 0,
  created BIGINT NOT NULL, rewarded_at BIGINT,
  CONSTRAINT referral_not_self CHECK (referrer_id <> referred_id)
);
CREATE INDEX IF NOT EXISTS idx_loyalty_referrals_referrer ON loyalty_referrals(referrer_id, id DESC);

CREATE TABLE IF NOT EXISTS loyalty_campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL CHECK (kind IN ('multiplier','first_purchase')),
  multiplier_pct INTEGER NOT NULL DEFAULT 100 CHECK (multiplier_pct BETWEEN 100 AND 1000),   -- 200 = double points
  bonus_points INTEGER NOT NULL DEFAULT 0 CHECK (bonus_points >= 0),                         -- for first_purchase
  starts BIGINT NOT NULL, ends BIGINT NOT NULL CHECK (ends > starts),
  weekdays TEXT NOT NULL DEFAULT '',                    -- '' = every day, else e.g. '0,6' for weekends (0 = Sunday, Lagos time)
  min_tier TEXT NOT NULL DEFAULT '',                    -- '' = everyone, else that tier and above
  category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL, -- empty = every product
  active INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);

