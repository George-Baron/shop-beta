-- VELTO-MART CARD, phase 3 structure. The card itself is issued and held by a licensed issuer; this only keeps references and status.
-- NEVER stored here: card number, CVV, BVN/NIN. Safe to run again.
CREATE TABLE IF NOT EXISTS card_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL CHECK (kind IN ('virtual','physical')),
  status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','under_review','info_needed','approved','rejected','issued','cancelled')),
  provider TEXT NOT NULL, provider_ref TEXT NOT NULL DEFAULT '',
  full_name TEXT NOT NULL DEFAULT '',
  delivery_name TEXT NOT NULL DEFAULT '', delivery_phone TEXT NOT NULL DEFAULT '', delivery_address TEXT NOT NULL DEFAULT '', delivery_city TEXT NOT NULL DEFAULT '', delivery_state TEXT NOT NULL DEFAULT '',
  status_note TEXT NOT NULL DEFAULT '',                       -- what the issuer or an administrator said (shown to the customer)
  replaces_card_id BIGINT,
  consent_version TEXT NOT NULL, consent_at BIGINT NOT NULL,
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_card_apps_user ON card_applications(user_id, id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_card_apps_provider_ref ON card_applications(provider, provider_ref) WHERE provider_ref <> '';
-- one open application per customer and kind
CREATE UNIQUE INDEX IF NOT EXISTS idx_card_apps_one_open ON card_applications(user_id, kind) WHERE status IN ('submitted','under_review','info_needed','approved');

CREATE TABLE IF NOT EXISTS cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  application_id BIGINT REFERENCES card_applications(id),
  kind TEXT NOT NULL CHECK (kind IN ('virtual','physical')),
  provider TEXT NOT NULL, provider_card_id TEXT NOT NULL,
  network TEXT NOT NULL DEFAULT '', last4 CHAR(4) NOT NULL, expiry_month SMALLINT, expiry_year SMALLINT,   -- only what the issuer permits us to show
  status TEXT NOT NULL DEFAULT 'inactive' CHECK (status IN ('inactive','active','frozen','blocked','replaced','expired','cancelled')),
  delivery_status TEXT NOT NULL DEFAULT '', balance BIGINT,   -- kobo, only if the issuer reports one (a bank-linked card has none); never mixed with the wallet
  created BIGINT NOT NULL, updated BIGINT NOT NULL,
  UNIQUE (provider, provider_card_id)
);
CREATE INDEX IF NOT EXISTS idx_cards_user ON cards(user_id, id DESC);

CREATE TABLE IF NOT EXISTS card_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id BIGINT, application_id BIGINT, user_id BIGINT NOT NULL,
  from_status TEXT NOT NULL DEFAULT '', to_status TEXT NOT NULL, actor TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_card_history_user ON card_status_history(user_id, id DESC);

-- Transaction metadata reported by the issuer (merchant and amount only).
CREATE TABLE IF NOT EXISTS card_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id BIGINT NOT NULL REFERENCES cards(id), user_id BIGINT NOT NULL REFERENCES users(id),
  provider_txn_id TEXT NOT NULL, amount BIGINT NOT NULL, currency CHAR(3) NOT NULL DEFAULT 'NGN',
  kind TEXT NOT NULL DEFAULT 'purchase', merchant TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'completed', occurred BIGINT NOT NULL, created BIGINT NOT NULL,
  UNIQUE (card_id, provider_txn_id)
);
CREATE INDEX IF NOT EXISTS idx_card_txns_card ON card_transactions(card_id, id DESC);

-- Every webhook the issuer sends, once (the issuer's event id is unique), so a repeat changes nothing.
CREATE TABLE IF NOT EXISTS card_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL, event_id TEXT NOT NULL, type TEXT NOT NULL, handled INTEGER NOT NULL DEFAULT 0, note TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL,
  UNIQUE (provider, event_id)
);
CREATE TABLE IF NOT EXISTS card_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, actor_id BIGINT, actor_name TEXT NOT NULL DEFAULT '', action TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);

-- Card issuing stays OFF until an issuer is chosen, contracted and tested. CARD_PROVIDER in the environment selects it.
