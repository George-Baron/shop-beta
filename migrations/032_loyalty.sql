-- VELTO REWARDS, phase 2 (first part): points, tiers, an immutable points ledger. Safe to run again.
CREATE TABLE IF NOT EXISTS loyalty_accounts (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
  points BIGINT NOT NULL DEFAULT 0 CHECK (points >= 0),      -- spendable balance
  lifetime BIGINT NOT NULL DEFAULT 0,                         -- earned for good, drives the tier
  redeemed BIGINT NOT NULL DEFAULT 0,
  tier TEXT NOT NULL DEFAULT 'Bronze',
  referral_code TEXT UNIQUE,
  created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS loyalty_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL CHECK (kind IN ('earn','reverse','redeem','expire','adjust','bonus')),
  points BIGINT NOT NULL,                                     -- + added, - taken (0 only for a reversal when nothing was left to take back)
  balance_after BIGINT NOT NULL,
  order_ref TEXT NOT NULL DEFAULT '',
  idem_key TEXT NOT NULL UNIQUE,                              -- one award per order, one redemption per request: points can never be given twice
  note TEXT NOT NULL DEFAULT '', actor TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_loyalty_ledger_user ON loyalty_ledger(user_id, id DESC);
CREATE OR REPLACE FUNCTION loyalty_ledger_immutable() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'loyalty ledger entries are immutable'; END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_loyalty_ledger_immutable ON loyalty_ledger;
CREATE TRIGGER trg_loyalty_ledger_immutable BEFORE UPDATE OR DELETE ON loyalty_ledger FOR EACH ROW EXECUTE FUNCTION loyalty_ledger_immutable();

DROP TRIGGER IF EXISTS trg_loyalty_ledger_no_truncate ON loyalty_ledger;
CREATE TRIGGER trg_loyalty_ledger_no_truncate BEFORE TRUNCATE ON loyalty_ledger FOR EACH STATEMENT EXECUTE FUNCTION loyalty_ledger_immutable();

CREATE TABLE IF NOT EXISTS loyalty_tiers (
  name TEXT PRIMARY KEY, min_lifetime BIGINT NOT NULL CHECK (min_lifetime >= 0), multiplier_pct INTEGER NOT NULL DEFAULT 100 CHECK (multiplier_pct >= 0),
  discount_pct INTEGER NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100), benefits TEXT NOT NULL DEFAULT '', sort INTEGER NOT NULL DEFAULT 0
);
