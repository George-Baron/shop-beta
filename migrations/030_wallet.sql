-- VELTO WALLET, phase 1: a closed-loop shopping wallet with an immutable double-entry ledger.
-- Amounts are stored in KOBO (minor units, BIGINT). Orders stay in whole Naira; the wallet code converts at the boundary.
-- Safe to run again. Nothing existing is changed or deleted.

-- Every balance lives on a ledger account. Customer wallets can never go below zero (CHECK). System accounts are the other side of every entry.
CREATE TABLE IF NOT EXISTS ledger_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('customer_wallet','gateway_clearing','order_clearing','refund_clearing','adjustment','reward_clearing')),
  user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  balance BIGINT NOT NULL DEFAULT 0,                       -- cached; always equals the sum of its ledger entries (see reconcile())
  pending BIGINT NOT NULL DEFAULT 0 CHECK (pending >= 0),  -- funds reserved for an order that is not finalised yet (part of balance, not spendable)
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','frozen')),
  frozen_reason TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  CONSTRAINT wallet_never_negative CHECK (kind <> 'customer_wallet' OR (balance >= 0 AND pending <= balance)),
  CONSTRAINT wallet_has_owner CHECK ((kind = 'customer_wallet') = (user_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_one_wallet_per_user ON ledger_accounts(user_id, currency) WHERE kind = 'customer_wallet';
CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_one_system_account ON ledger_accounts(kind, currency) WHERE kind <> 'customer_wallet';

-- One business event (a funding, a purchase, a refund, an adjustment). idem_key makes every posting safe to retry.
CREATE TABLE IF NOT EXISTS wallet_txns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  idem_key TEXT NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  type TEXT NOT NULL CHECK (type IN ('deposit','purchase','refund','reward','adjustment','withdrawal')),
  amount BIGINT NOT NULL CHECK (amount > 0),
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  direction TEXT NOT NULL CHECK (direction IN ('credit','debit')),   -- as seen by the customer's wallet
  balance_before BIGINT NOT NULL, balance_after BIGINT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  order_ref TEXT NOT NULL DEFAULT '', gateway TEXT NOT NULL DEFAULT '', gateway_ref TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed','reversed')),
  actor TEXT NOT NULL DEFAULT '', reason TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wallet_txns_user ON wallet_txns(user_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_wallet_txns_order ON wallet_txns(order_ref) WHERE order_ref <> '';

-- The double entry: every txn has entries that add up to exactly zero. Entries can never be changed or deleted.
CREATE TABLE IF NOT EXISTS ledger_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  txn_id BIGINT NOT NULL REFERENCES wallet_txns(id) ON DELETE RESTRICT,
  account_id BIGINT NOT NULL REFERENCES ledger_accounts(id) ON DELETE RESTRICT,
  amount BIGINT NOT NULL CHECK (amount <> 0),              -- + credit to the account, - debit from it
  balance_after BIGINT NOT NULL,
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_entries_account ON ledger_entries(account_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_ledger_entries_txn ON ledger_entries(txn_id);

CREATE OR REPLACE FUNCTION ledger_entries_immutable() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'ledger entries are immutable'; END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_ledger_entries_immutable ON ledger_entries;
CREATE TRIGGER trg_ledger_entries_immutable BEFORE UPDATE OR DELETE ON ledger_entries FOR EACH ROW EXECUTE FUNCTION ledger_entries_immutable();
DROP TRIGGER IF EXISTS trg_ledger_entries_no_truncate ON ledger_entries;
CREATE TRIGGER trg_ledger_entries_no_truncate BEFORE TRUNCATE ON ledger_entries FOR EACH STATEMENT EXECUTE FUNCTION ledger_entries_immutable();

-- Only a txn's status may change (completed -> reversed), never its money fields.
CREATE OR REPLACE FUNCTION wallet_txns_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'wallet transactions cannot be deleted'; END IF;
  IF NEW.amount <> OLD.amount OR NEW.user_id <> OLD.user_id OR NEW.type <> OLD.type OR NEW.ref <> OLD.ref OR NEW.balance_after <> OLD.balance_after THEN
    RAISE EXCEPTION 'wallet transaction money fields are immutable';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_wallet_txns_guard ON wallet_txns;
CREATE TRIGGER trg_wallet_txns_guard BEFORE UPDATE OR DELETE ON wallet_txns FOR EACH ROW EXECUTE FUNCTION wallet_txns_guard();

-- A top-up attempt. The wallet is credited only after the gateway itself confirms the payment (never from the browser).
CREATE TABLE IF NOT EXISTS wallet_funding (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  amount BIGINT NOT NULL CHECK (amount > 0),
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  gateway TEXT NOT NULL DEFAULT 'paystack',
  status TEXT NOT NULL DEFAULT 'initiated' CHECK (status IN ('initiated','success','failed','mismatch')),
  note TEXT NOT NULL DEFAULT '',
  txn_id BIGINT REFERENCES wallet_txns(id),
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wallet_funding_user ON wallet_funding(user_id, id DESC);

-- Money held for an order that is awaiting a gateway payment (partial wallet payment). Released if the order is not paid.
CREATE TABLE IF NOT EXISTS wallet_reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_ref TEXT NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  amount BIGINT NOT NULL CHECK (amount > 0),
  status TEXT NOT NULL DEFAULT 'held' CHECK (status IN ('held','captured','released')),
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);

-- Every money-moving action by staff, with who, why and the reference. Append-only.
CREATE TABLE IF NOT EXISTS wallet_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT, actor_id BIGINT, actor_name TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wallet_audit_user ON wallet_audit(user_id, id DESC);

