-- Phase 2: pharmacy groundwork. Everything here is inert unless PHARMACY_ENABLED=1; with the switch off the app hides every pharmacy product.

-- Medicine fields on products
ALTER TABLE products
  ADD COLUMN is_medicine INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN rx_required INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN nafdac_no TEXT NOT NULL DEFAULT '',
  ADD COLUMN batch_no TEXT NOT NULL DEFAULT '',
  ADD COLUMN expiry_date TEXT NOT NULL DEFAULT '',          -- YYYY-MM-DD of the batch
  ADD COLUMN storage_temp TEXT NOT NULL DEFAULT 'ambient',  -- ambient | cool | cold
  ADD COLUMN temp_sensitive INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN max_qty INTEGER NOT NULL DEFAULT 0,            -- 0 = use the shop-wide limit
  ADD COLUMN pharm_status TEXT NOT NULL DEFAULT 'none',     -- none | pending | approved | rejected (decided by our superintendent pharmacist)
  ADD COLUMN pharm_approved_by TEXT NOT NULL DEFAULT '',
  ADD COLUMN pharm_approved_at BIGINT,
  ADD COLUMN is_pharmacy INTEGER NOT NULL DEFAULT 0;        -- kept up to date by the trigger below: in the pharmacy department, or marked as a medicine
CREATE OR REPLACE FUNCTION products_set_is_pharmacy() RETURNS trigger AS $$
BEGIN NEW.is_pharmacy := CASE WHEN NEW.store = 'pharmacy' OR NEW.is_medicine = 1 THEN 1 ELSE 0 END; RETURN NEW; END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER products_is_pharmacy BEFORE INSERT OR UPDATE ON products FOR EACH ROW EXECUTE FUNCTION products_set_is_pharmacy();
UPDATE products SET is_medicine = is_medicine;               -- fires the trigger for existing rows (demo pharmacy items included)
CREATE INDEX idx_products_pharmacy ON products(is_pharmacy) WHERE is_pharmacy = 1;

-- Partner pharmacies (one per pickup point)
CREATE TABLE pharmacies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id BIGINT NOT NULL UNIQUE REFERENCES partners(id),
  pharmacy_name TEXT NOT NULL,
  premises_licence_no TEXT NOT NULL DEFAULT '',
  epharmacy_licence_no TEXT NOT NULL DEFAULT '',
  superintendent_name TEXT NOT NULL DEFAULT '',
  superintendent_reg_no TEXT NOT NULL DEFAULT '',
  licence_year INTEGER NOT NULL DEFAULT 0,                  -- licences run 1 January to 31 December
  licence_expires BIGINT NOT NULL DEFAULT 0,                -- end of that year, Lagos time
  agreement_file TEXT NOT NULL DEFAULT '',                  -- name of the signed service agreement in the private pharmacy-docs bucket
  agreement_name TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft',                     -- draft | pending | approved | suspended
  approved_by TEXT NOT NULL DEFAULT '',
  approved_at BIGINT,
  review_note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL
);
ALTER TABLE users
  ADD COLUMN pharmacy_id BIGINT REFERENCES pharmacies(id),  -- a pharmacist of that pharmacy; NULL for our own superintendent pharmacist
  ADD COLUMN reg_no TEXT NOT NULL DEFAULT '',               -- pharmacist's PCN registration number
  ADD COLUMN gdp INTEGER NOT NULL DEFAULT 0;                -- rider/courier meets Good Distribution Practice (cold-chain items)

-- Buyer identity (as little as possible; the ID number is encrypted by the app)
CREATE TABLE buyer_identity (
  user_id BIGINT PRIMARY KEY REFERENCES users(id),
  full_name TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  phone_verified_at BIGINT,
  id_type TEXT NOT NULL DEFAULT '',                         -- nin | voters | passport | drivers
  id_last4 TEXT NOT NULL DEFAULT '',
  id_number_enc TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'none',                      -- none | submitted | verified | rejected
  verified_by TEXT NOT NULL DEFAULT '',
  verified_at BIGINT,
  note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  retain_until BIGINT NOT NULL
);
CREATE TABLE otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  target TEXT NOT NULL,
  code_hash TEXT NOT NULL,
  expires BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  used INTEGER NOT NULL DEFAULT 0,
  created BIGINT NOT NULL
);
CREATE INDEX idx_otps_user ON otps(user_id, id DESC);
CREATE TABLE sms_outbox (                                    -- like the email outbox: stored here, and sent when an SMS gateway is configured
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_phone TEXT NOT NULL, body TEXT NOT NULL, sent INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);

-- Prescriptions
CREATE TABLE prescriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'submitted',                 -- submitted | approved | partly_approved | rejected | needs_info | expired | cancelled
  file_key TEXT NOT NULL,                                   -- encrypted copy in the private prescriptions bucket
  file_mime TEXT NOT NULL DEFAULT '',
  file_sha256 TEXT NOT NULL,
  prescriber_name TEXT NOT NULL,
  prescriber_reg_no TEXT NOT NULL,
  prescriber_council TEXT NOT NULL DEFAULT 'MDCN',
  prescriber_contact TEXT NOT NULL DEFAULT '',
  prescriber_address TEXT NOT NULL DEFAULT '',
  patient_enc TEXT NOT NULL DEFAULT '',                     -- patient name and details, encrypted
  fingerprint TEXT NOT NULL,                                -- keyed hash of prescriber + patient + date, to spot the same prescription used twice
  issued_on BIGINT NOT NULL,
  valid_until BIGINT NOT NULL,                              -- six months after issue
  duration_days INTEGER NOT NULL DEFAULT 0,
  max_fills INTEGER NOT NULL DEFAULT 1,
  fills_used INTEGER NOT NULL DEFAULT 0,
  fills_reserved INTEGER NOT NULL DEFAULT 0,
  refill_interval_days INTEGER NOT NULL DEFAULT 0,
  last_filled_at BIGINT,
  reviewer_id BIGINT REFERENCES users(id),
  reviewer_name TEXT NOT NULL DEFAULT '',
  reviewer_reg_no TEXT NOT NULL DEFAULT '',
  reviewed_at BIGINT,
  register_check TEXT NOT NULL DEFAULT '',                  -- what the pharmacist found when looking the prescriber up on the council register
  decision_note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  retain_until BIGINT NOT NULL
);
CREATE INDEX idx_rx_user ON prescriptions(user_id, id DESC);
CREATE INDEX idx_rx_hash ON prescriptions(file_sha256);
CREATE INDEX idx_rx_fp ON prescriptions(fingerprint);
CREATE TABLE prescription_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id BIGINT NOT NULL REFERENCES prescriptions(id),
  product_id BIGINT REFERENCES products(id),
  drug_text TEXT NOT NULL,
  qty_written INTEGER NOT NULL CHECK (qty_written > 0)
);
CREATE INDEX idx_rxl_rx ON prescription_lines(prescription_id);
CREATE TABLE order_rx (
  order_id BIGINT NOT NULL REFERENCES orders(id),
  prescription_id BIGINT NOT NULL REFERENCES prescriptions(id),
  PRIMARY KEY (order_id, prescription_id)
);
CREATE INDEX idx_order_rx_rx ON order_rx(prescription_id);

-- Orders and items
ALTER TABLE orders
  ADD COLUMN is_pharmacy INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN pharmacy_id BIGINT REFERENCES pharmacies(id),
  ADD COLUMN rx_required INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN rx_status TEXT NOT NULL DEFAULT 'none',        -- none | submitted | needs_info | verified | rejected
  ADD COLUMN rx_fill_reserved INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN temp_sensitive INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN pharm_hold INTEGER NOT NULL DEFAULT 0,         -- 1 while a suspicious-order flag is open
  ADD COLUMN recipient_name TEXT NOT NULL DEFAULT '';       -- who the rider confirmed at the door
CREATE INDEX idx_orders_rx ON orders(rx_status) WHERE rx_required = 1;
ALTER TABLE order_items ADD COLUMN rx_line_id BIGINT REFERENCES prescription_lines(id);

CREATE TABLE pharmacy_flags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  kind TEXT NOT NULL,                                       -- repeat_person | repeat_address | repeat_payment | large_quantity | reused_prescription
  detail TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'open',                      -- open | cleared | confirmed
  reviewed_by TEXT NOT NULL DEFAULT '',
  reviewed_at BIGINT,
  note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);
CREATE INDEX idx_pflags_open ON pharmacy_flags(status, id DESC);

CREATE TABLE medicine_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  reason TEXT NOT NULL,                                     -- tampered | expired | wrong_item | damaged | other
  note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'requested',                 -- requested | approved | rejected | collected
  resolution TEXT NOT NULL DEFAULT '',
  restock INTEGER NOT NULL DEFAULT 0,                       -- returned medicines are never put back on sale automatically
  handled_by TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL
);

-- Every time someone other than the owner opens a sensitive record
CREATE TABLE pharmacy_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT, user_name TEXT NOT NULL DEFAULT '', role TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL, entity TEXT NOT NULL DEFAULT '', entity_id TEXT NOT NULL DEFAULT '', detail TEXT NOT NULL DEFAULT '',
  ip TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_paudit_created ON pharmacy_audit(created DESC);

