ALTER TABLE buyer_identity ENABLE ROW LEVEL SECURITY;
ALTER TABLE otps ENABLE ROW LEVEL SECURITY;
ALTER TABLE sms_outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE prescriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE prescription_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_rx ENABLE ROW LEVEL SECURITY;
ALTER TABLE pharmacy_flags ENABLE ROW LEVEL SECURITY;
ALTER TABLE medicine_returns ENABLE ROW LEVEL SECURITY;
ALTER TABLE pharmacy_audit ENABLE ROW LEVEL SECURITY;
