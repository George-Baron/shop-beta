-- Bulk product import/export: extra product fields and an import/export history.
-- Additive only: existing products keep working and no existing value changes.
ALTER TABLE products
  ADD COLUMN barcode TEXT NOT NULL DEFAULT '',
  ADD COLUMN subcategory TEXT NOT NULL DEFAULT '',
  ADD COLUMN cost_price INTEGER CHECK (cost_price IS NULL OR cost_price >= 0),
  ADD COLUMN min_stock INTEGER NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  ADD COLUMN unit TEXT NOT NULL DEFAULT '',
  ADD COLUMN tax_pct NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (tax_pct >= 0 AND tax_pct <= 100),
  ADD COLUMN weight_kg NUMERIC(10,3) CHECK (weight_kg IS NULL OR weight_kg >= 0);

-- A barcode identifies one product (blank barcodes are not compared). SKU is not forced unique here because shops already
-- have products with repeated SKUs; the importer refuses ambiguous SKUs instead.
CREATE UNIQUE INDEX idx_products_barcode ON products (barcode) WHERE barcode <> '';
CREATE INDEX idx_products_sku ON products (sku) WHERE sku <> '';

CREATE TABLE catalog_imports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('import','export')),
  mode TEXT NOT NULL DEFAULT '',
  filename TEXT NOT NULL DEFAULT '',
  user_id BIGINT,
  user_name TEXT NOT NULL DEFAULT '',
  total INTEGER NOT NULL DEFAULT 0,
  created_n INTEGER NOT NULL DEFAULT 0,
  updated_n INTEGER NOT NULL DEFAULT 0,
  failed_n INTEGER NOT NULL DEFAULT 0,
  errors TEXT NOT NULL DEFAULT '[]',          -- JSON list of {line, name, sku, problems[]} for the downloadable error report
  detail TEXT NOT NULL DEFAULT '',            -- export filter, for example
  created BIGINT NOT NULL
);
CREATE INDEX idx_catalog_imports_created ON catalog_imports (created DESC);
