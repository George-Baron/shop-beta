-- VELTO AI OPERATIONS MANAGER, phase 1: command centre, permissions engine, approval engine, audit trail, exceptions, tasks, assistant chats.
-- It reads the EXISTING orders, stock, riders, suppliers, dropship and trade tables; it does not copy them and it adds no second inventory.
-- Nothing here changes existing data. All times are epoch seconds (BIGINT), like the rest of the schema.
-- RLS is switched on for every table with no policy: nobody can reach these tables through the Supabase public API. The app connects as owner and checks access in code.

-- Settings of the AI: autonomy modes, approval thresholds, switched-off permissions, agent switches. One JSON value per key.
CREATE TABLE IF NOT EXISTS ops_config (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL,
  updated BIGINT NOT NULL,
  updated_by TEXT NOT NULL DEFAULT ''
);

-- Who may approve what. The owner (users.role = 'admin') is always level 4. An employee approves up to max_level (2 supervisor, 3 senior manager, 4 finance/executive).
-- emergency = 1 marks a designated executive who may approve emergency actions alone.
CREATE TABLE IF NOT EXISTS ops_approvers (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  max_level SMALLINT NOT NULL CHECK (max_level BETWEEN 2 AND 4),
  emergency SMALLINT NOT NULL DEFAULT 0 CHECK (emergency IN (0,1)),
  created BIGINT NOT NULL,
  created_by TEXT NOT NULL DEFAULT ''
);

-- An action that needs a human decision. payload is the exact action that was reviewed; payload_hash proves it was not changed after approval.
CREATE SEQUENCE IF NOT EXISTS ops_approval_seq START 1;
CREATE TABLE IF NOT EXISTS ops_approvals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('APR-' || lpad(nextval('ops_approval_seq')::text, 5, '0')),
  action_type TEXT NOT NULL,
  category TEXT NOT NULL,
  department TEXT NOT NULL,
  level_required SMALLINT NOT NULL CHECK (level_required BETWEEN 1 AND 4),
  required_approvals SMALLINT NOT NULL DEFAULT 1 CHECK (required_approvals BETWEEN 1 AND 3),
  amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  amount_ngn NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (amount_ngn >= 0),   -- this action's own amount in Naira, converted at the verified rate on the day
  effective_ngn NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (effective_ngn >= 0),   -- the amount that decided the level: this one plus earlier ones to the same counterparty inside the window (no splitting)
  value_unknown SMALLINT NOT NULL DEFAULT 0 CHECK (value_unknown IN (0,1)),    -- 1 = no verified exchange rate, so the level was set to the highest
  summary TEXT NOT NULL DEFAULT '',
  justification TEXT NOT NULL DEFAULT '',
  risk TEXT NOT NULL DEFAULT 'low' CHECK (risk IN ('low','medium','high')),
  payload JSONB NOT NULL DEFAULT '{}',
  payload_hash TEXT NOT NULL,
  related_type TEXT NOT NULL DEFAULT '',
  related_id TEXT NOT NULL DEFAULT '',
  counterparty TEXT NOT NULL DEFAULT '',                                  -- supplier / customer / provider the money or promise is about (used to stop split transactions)
  requested_by_kind TEXT NOT NULL CHECK (requested_by_kind IN ('ai','user')),
  requested_by_agent TEXT NOT NULL DEFAULT '',
  requested_by_user BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('draft','pending','approved','rejected','returned','expired','executing','completed','failed','cancelled')),
  emergency SMALLINT NOT NULL DEFAULT 0 CHECK (emergency IN (0,1)),
  emergency_reason TEXT NOT NULL DEFAULT '',
  executor TEXT NOT NULL DEFAULT 'system' CHECK (executor IN ('system','human')),   -- 'human' = money or a signature: the AI never performs it, a person records that they did
  deadline BIGINT NOT NULL,
  approved_hash TEXT,
  execution_result JSONB,
  executed_at BIGINT,
  idem_key TEXT,
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_approvals_status ON ops_approvals(status, created DESC);
CREATE INDEX IF NOT EXISTS idx_ops_approvals_counterparty ON ops_approvals(category, counterparty, created DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ops_approvals_open ON ops_approvals(idem_key) WHERE idem_key IS NOT NULL AND status IN ('pending','approved','executing');

-- One row per person per approval. Two-person rules count distinct people.
CREATE TABLE IF NOT EXISTS ops_approval_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  approval_id BIGINT NOT NULL REFERENCES ops_approvals(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  user_name TEXT NOT NULL DEFAULT '',
  decision TEXT NOT NULL CHECK (decision IN ('approve','reject','return')),
  note TEXT NOT NULL DEFAULT '',
  payload_hash TEXT NOT NULL,                                             -- what this person was shown
  created BIGINT NOT NULL,
  UNIQUE (approval_id, user_id)
);

-- Segregation of duties: which step of a purchase or payment was done by whom. One row per object and step.
CREATE TABLE IF NOT EXISTS ops_sod_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  related_type TEXT NOT NULL,
  related_id TEXT NOT NULL,
  step TEXT NOT NULL CHECK (step IN ('request_create','supplier_approve','po_approve','goods_receipt','invoice_verify','payment_authorize')),
  actor TEXT NOT NULL,                                                    -- 'ai' or 'user:<id>'
  approval_id BIGINT,
  created BIGINT NOT NULL,
  UNIQUE (related_type, related_id, step, actor)                         -- two people may both carry out the same step (two-person approval); one person cannot hold two conflicting ones
);

-- The AI's own audit trail. APPEND ONLY: the database refuses updates and deletes. A correction is a new row with reversal_of set.
-- No foreign keys on purpose: deleting a user or an order must never be blocked by, or rewrite, the history.
CREATE SEQUENCE IF NOT EXISTS ops_action_seq START 1;
CREATE TABLE IF NOT EXISTS ops_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('ACT-' || lpad(nextval('ops_action_seq')::text, 6, '0')),
  agent TEXT NOT NULL,
  actor_kind TEXT NOT NULL CHECK (actor_kind IN ('ai_autonomous','ai_approved','human','integration','system')),
  actor_user BIGINT,
  actor_name TEXT NOT NULL DEFAULT '',
  action_type TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  related_type TEXT NOT NULL DEFAULT '',
  related_id TEXT NOT NULL DEFAULT '',
  mode TEXT NOT NULL DEFAULT '',
  level SMALLINT,
  status TEXT NOT NULL CHECK (status IN ('done','recommended','pending_approval','blocked','failed','read')),
  data_used JSONB,                                                        -- the facts the AI looked at (kept small)
  recommendation TEXT NOT NULL DEFAULT '',
  result JSONB,
  approval_id BIGINT,
  approver TEXT NOT NULL DEFAULT '',
  external_ref TEXT NOT NULL DEFAULT '',
  error TEXT NOT NULL DEFAULT '',
  reversal_of BIGINT,
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_actions_created ON ops_actions(id DESC);
CREATE INDEX IF NOT EXISTS idx_ops_actions_related ON ops_actions(related_type, related_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_ops_actions_agent ON ops_actions(agent, id DESC);

CREATE OR REPLACE FUNCTION ops_actions_immutable() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'ops_actions is append-only'; END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_ops_actions_immutable ON ops_actions;
CREATE TRIGGER trg_ops_actions_immutable BEFORE UPDATE OR DELETE ON ops_actions FOR EACH ROW EXECUTE FUNCTION ops_actions_immutable();
DROP TRIGGER IF EXISTS trg_ops_actions_no_truncate ON ops_actions;
CREATE TRIGGER trg_ops_actions_no_truncate BEFORE TRUNCATE ON ops_actions FOR EACH STATEMENT EXECUTE FUNCTION ops_actions_immutable();

-- Problems the AI found (or staff raised). dedupe_key keeps one open row per problem, however often the checks run.
CREATE SEQUENCE IF NOT EXISTS ops_exception_seq START 1;
CREATE TABLE IF NOT EXISTS ops_exceptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE DEFAULT ('EXC-' || lpad(nextval('ops_exception_seq')::text, 5, '0')),
  kind TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('informational','low','medium','high','critical')),
  title TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  impact TEXT NOT NULL DEFAULT '',
  recommended_action TEXT NOT NULL DEFAULT '',
  department TEXT NOT NULL DEFAULT '',
  related_type TEXT NOT NULL DEFAULT '',
  related_id TEXT NOT NULL DEFAULT '',
  dedupe_key TEXT NOT NULL,
  auto INTEGER NOT NULL DEFAULT 1 CHECK (auto IN (0,1)),                  -- 1 = raised by the monitor and cleared by it when the condition goes away
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','acknowledged','resolved','dismissed')),
  detected_by TEXT NOT NULL DEFAULT '',
  notified_severity TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL,
  resolved_at BIGINT,
  resolved_by TEXT NOT NULL DEFAULT '',
  resolution TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_ops_exceptions_open ON ops_exceptions(dedupe_key) WHERE status IN ('open','acknowledged');
CREATE INDEX IF NOT EXISTS idx_ops_exceptions_status ON ops_exceptions(status, severity, created DESC);

-- Internal operational tasks the AI (or staff) creates.
CREATE TABLE IF NOT EXISTS ops_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  department TEXT NOT NULL DEFAULT '',
  priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','done','cancelled')),
  due BIGINT,
  related_type TEXT NOT NULL DEFAULT '',
  related_id TEXT NOT NULL DEFAULT '',
  assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_by_kind TEXT NOT NULL DEFAULT 'ai' CHECK (created_by_kind IN ('ai','user')),
  created_by TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_tasks_status ON ops_tasks(status, priority, created DESC);

-- Conversations with the assistant in the command centre (so management can see what was asked and answered).
CREATE TABLE IF NOT EXISTS ops_chats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  updated BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS ops_chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id BIGINT NOT NULL REFERENCES ops_chats(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('user','assistant')),
  content TEXT NOT NULL,
  actions JSONB,                                                          -- what the backend says happened (done / recommended / pending approval / blocked / failed)
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ops_chat_messages ON ops_chat_messages(chat_id, id);

