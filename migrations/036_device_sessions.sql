-- Mobile app sign-in: short-lived access tokens plus rotating refresh tokens, one row per signed-in device. Only hashes are stored. Safe to run again.
CREATE TABLE IF NOT EXISTS device_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  access_hash TEXT NOT NULL UNIQUE, refresh_hash TEXT NOT NULL UNIQUE, prev_refresh_hash TEXT NOT NULL DEFAULT '', rotated_at BIGINT NOT NULL DEFAULT 0,
  device_name TEXT NOT NULL DEFAULT '', platform TEXT NOT NULL DEFAULT '', app_version TEXT NOT NULL DEFAULT '',
  access_expires BIGINT NOT NULL, refresh_expires BIGINT NOT NULL,
  created BIGINT NOT NULL, last_seen BIGINT NOT NULL, last_ip TEXT NOT NULL DEFAULT '',
  revoked_at BIGINT, revoked_reason TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_device_sessions_user ON device_sessions(user_id, id DESC);
