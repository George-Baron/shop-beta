-- Global Trade phase 4: import procurement and international suppliers.
-- Supplier payments are records staff enter about money they paid outside this system. The platform never moves supplier money.
CREATE TABLE supplier_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id BIGINT NOT NULL REFERENCES international_suppliers(id) ON DELETE RESTRICT,
  po_id BIGINT REFERENCES import_purchase_orders(id) ON DELETE SET NULL, currency TEXT NOT NULL REFERENCES trade_currencies(code),
  amount NUMERIC(18,4) NOT NULL CHECK (amount > 0), fx_rate_to_ngn NUMERIC(28,12), amount_ngn NUMERIC(18,4),
  method TEXT NOT NULL DEFAULT 'bank_transfer', reference TEXT NOT NULL DEFAULT '', paid_on DATE NOT NULL, note TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_spay_supplier ON supplier_payments(supplier_id, paid_on DESC);
CREATE INDEX idx_spay_po ON supplier_payments(po_id) WHERE po_id IS NOT NULL;

-- one shipment record per purchase order
CREATE UNIQUE INDEX uq_ish_po ON import_shipments(po_id) WHERE po_id IS NOT NULL;
-- a supplier catalogue line is identified by its supplier SKU (when it has one)
CREATE UNIQUE INDEX uq_sprod_sku ON supplier_products(supplier_id, lower(supplier_sku)) WHERE supplier_sku <> '';
-- uploaded supplier files are stored privately; this is the stored file name
ALTER TABLE trade_documents ADD COLUMN IF NOT EXISTS stored_name TEXT NOT NULL DEFAULT '';
ALTER TABLE supplier_payments ENABLE ROW LEVEL SECURITY;
