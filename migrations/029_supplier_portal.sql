-- Step 7 of dropshipping: the optional supplier portal. A supplier signs in (role 'supplier'), sees only its own purchase orders, confirms or rejects them and adds tracking.
-- Anything that affects price or stock is only a proposal until an admin approves it. Safe to run again. Nothing is deleted or rewritten.

ALTER TABLE users ADD COLUMN IF NOT EXISTS supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL;   -- role 'supplier': which supplier this person works for
CREATE INDEX IF NOT EXISTS idx_users_supplier ON users(supplier_id) WHERE supplier_id IS NOT NULL;

-- A supplier saying "we cannot supply this" does not change the item. It waits here until an admin accepts it (the item becomes a problem and the customer is told)
-- or declines it (the supplier is asked to supply it after all).
ALTER TABLE dropship_lines ADD COLUMN IF NOT EXISTS supplier_response TEXT NOT NULL DEFAULT '' CHECK (supplier_response IN ('','rejected'));
ALTER TABLE dropship_lines ADD COLUMN IF NOT EXISTS supplier_response_kind TEXT NOT NULL DEFAULT '';
ALTER TABLE dropship_lines ADD COLUMN IF NOT EXISTS supplier_response_note TEXT NOT NULL DEFAULT '';
ALTER TABLE dropship_lines ADD COLUMN IF NOT EXISTS supplier_response_at BIGINT;

-- A supplier proposing a new price or new stock for one of its products. Nothing changes until an admin approves it.
CREATE TABLE IF NOT EXISTS supplier_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES dropship_products(product_id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('price','stock')),
  old_cost NUMERIC(14,2), old_ship_cost NUMERIC(14,2), old_stock INTEGER,
  new_cost NUMERIC(14,2) CHECK (new_cost IS NULL OR new_cost > 0), new_ship_cost NUMERIC(14,2) CHECK (new_ship_cost IS NULL OR new_ship_cost >= 0),
  new_stock INTEGER CHECK (new_stock IS NULL OR new_stock >= 0),
  note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  created_by BIGINT, created_by_name TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL,
  decided_by TEXT NOT NULL DEFAULT '', decided_at BIGINT, decision_note TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_supplier_requests_pending ON supplier_requests(product_id, kind) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS idx_supplier_requests_supplier ON supplier_requests(supplier_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_supplier_requests_status ON supplier_requests(status, id DESC);
ALTER TABLE supplier_requests ENABLE ROW LEVEL SECURITY;
