-- Partner stores (vendors): many stores, each with its own page, up to 3 departments each, products reviewed by us,
-- commission recorded per order line, and a payout ledger. "partners" (pickup points) and "stores" (departments) already exist, so this module says "vendor".
CREATE TABLE vendors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, tagline TEXT NOT NULL DEFAULT '', about TEXT NOT NULL DEFAULT '',
  logo TEXT NOT NULL DEFAULT '', banner TEXT NOT NULL DEFAULT '', emoji TEXT NOT NULL DEFAULT '🏪',
  contact_name TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '', city TEXT NOT NULL DEFAULT '', opening_hours TEXT NOT NULL DEFAULT '',
  reg_no TEXT NOT NULL DEFAULT '',                          -- business registration number (CAC), checked by us during evaluation
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','suspended')),   -- pending = under evaluation, not shown to customers
  status_note TEXT NOT NULL DEFAULT '',
  commission_pct NUMERIC(5,2) NOT NULL DEFAULT 10 CHECK (commission_pct >= 0 AND commission_pct <= 60),
  partner_id BIGINT REFERENCES partners(id) ON DELETE SET NULL,   -- the pickup point riders collect from (created when we approve the store)
  lat DOUBLE PRECISION, lng DOUBLE PRECISION,
  created BIGINT NOT NULL, approved_at BIGINT
);
CREATE INDEX idx_vendors_status ON vendors(status, name);
CREATE INDEX idx_vendors_name_trgm ON vendors USING gin (lower(name) gin_trgm_ops);

CREATE TABLE vendor_departments (
  vendor_id BIGINT NOT NULL REFERENCES vendors(id) ON DELETE CASCADE,
  store TEXT NOT NULL REFERENCES stores(slug),
  commission_pct NUMERIC(5,2) CHECK (commission_pct IS NULL OR (commission_pct >= 0 AND commission_pct <= 60)),   -- optional override of the store's rate for this department
  PRIMARY KEY (vendor_id, store)
);
CREATE OR REPLACE FUNCTION vendor_dept_limit() RETURNS trigger AS $$
BEGIN
  IF (SELECT count(*) FROM vendor_departments WHERE vendor_id = NEW.vendor_id) >= 3 THEN
    RAISE EXCEPTION 'A partner store can have at most 3 departments.' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER vendor_dept_limit BEFORE INSERT ON vendor_departments FOR EACH ROW EXECUTE FUNCTION vendor_dept_limit();

ALTER TABLE users ADD COLUMN vendor_id BIGINT REFERENCES vendors(id) ON DELETE SET NULL;     -- role 'vendor': which store this person runs
CREATE INDEX idx_users_vendor ON users(vendor_id) WHERE vendor_id IS NOT NULL;

ALTER TABLE products
  ADD COLUMN vendor_id BIGINT REFERENCES vendors(id),                      -- NULL = our own product
  ADD COLUMN listing TEXT NOT NULL DEFAULT 'approved' CHECK (listing IN ('pending','approved','rejected')),   -- partner products wait for our review
  ADD COLUMN listing_note TEXT NOT NULL DEFAULT '';
CREATE INDEX idx_products_vendor ON products(vendor_id, listing, active) WHERE vendor_id IS NOT NULL;

ALTER TABLE order_items
  ADD COLUMN vendor_id BIGINT,                                             -- copied at checkout so history survives product edits
  ADD COLUMN commission_pct NUMERIC(5,2) NOT NULL DEFAULT 0,
  ADD COLUMN commission INTEGER NOT NULL DEFAULT 0;                        -- Naira we keep from this line (price x qty x rate)
CREATE INDEX idx_order_items_vendor ON order_items(vendor_id) WHERE vendor_id IS NOT NULL;

CREATE TABLE vendor_payouts (                                              -- money we have paid out to a store; balance = delivered sales - commission - payouts
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL REFERENCES vendors(id),
  amount INTEGER NOT NULL CHECK (amount > 0), method TEXT NOT NULL DEFAULT 'transfer', reference TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_vendor_payouts_vendor ON vendor_payouts(vendor_id, id DESC);

ALTER TABLE vendors ENABLE ROW LEVEL SECURITY;
ALTER TABLE vendor_departments ENABLE ROW LEVEL SECURITY;
ALTER TABLE vendor_payouts ENABLE ROW LEVEL SECURITY;
