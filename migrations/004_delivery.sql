-- Step 6A: pickup partners, riders, customer location, delivery stages, handover code, rider tracking.
CREATE TABLE partners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, address TEXT NOT NULL DEFAULT '', state TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL,
  radius_km NUMERIC NOT NULL DEFAULT 15,
  is_default INTEGER NOT NULL DEFAULT 0,   -- the pickup point for products that have no partner of their own
  active INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);
ALTER TABLE users ADD COLUMN coverage TEXT NOT NULL DEFAULT '';   -- riders: comma-separated states they deliver in (empty = everywhere)
ALTER TABLE users ADD COLUMN active INTEGER NOT NULL DEFAULT 1;   -- staff can be switched off without deleting
ALTER TABLE products ADD COLUMN partner_id BIGINT REFERENCES partners(id) ON DELETE SET NULL;
CREATE INDEX idx_products_partner ON products(partner_id) WHERE partner_id IS NOT NULL;

ALTER TABLE orders
  ADD COLUMN lat DOUBLE PRECISION, ADD COLUMN lng DOUBLE PRECISION, ADD COLUMN landmark TEXT NOT NULL DEFAULT '',
  ADD COLUMN dist_km NUMERIC, ADD COLUMN eta_min INTEGER, ADD COLUMN promised_at BIGINT,
  ADD COLUMN rider_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN accepted_at BIGINT, ADD COLUMN picked_up_at BIGINT, ADD COLUMN on_way_at BIGINT, ADD COLUMN delivered_at BIGINT,
  ADD COLUMN delivered_lat DOUBLE PRECISION, ADD COLUMN delivered_lng DOUBLE PRECISION,
  ADD COLUMN handover_nonce TEXT NOT NULL DEFAULT '',      -- the 6-digit code is derived from this plus a server secret; it is never stored itself
  ADD COLUMN handover_attempts INTEGER NOT NULL DEFAULT 0, ADD COLUMN handover_locked INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN cash_collected BIGINT;
CREATE INDEX idx_orders_rider ON orders(rider_id, status) WHERE rider_id IS NOT NULL;

CREATE TABLE order_pickups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  partner_id BIGINT NOT NULL REFERENCES partners(id),
  dist_km NUMERIC, eta_min INTEGER, picked_up_at BIGINT,
  UNIQUE (order_id, partner_id)
);
CREATE TABLE rider_points (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  rider_id BIGINT NOT NULL, lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_rider_points_order ON rider_points(order_id, id DESC);
CREATE INDEX idx_rider_points_created ON rider_points(created);
-- Cached map-provider answers (routes and address searches), so the provider is not called on every page view.
CREATE TABLE geo_cache (key TEXT PRIMARY KEY, value JSONB NOT NULL, created BIGINT NOT NULL);
CREATE INDEX idx_geo_cache_created ON geo_cache(created);
ALTER TABLE partners ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_pickups ENABLE ROW LEVEL SECURITY;
ALTER TABLE rider_points ENABLE ROW LEVEL SECURITY;
ALTER TABLE geo_cache ENABLE ROW LEVEL SECURITY;
