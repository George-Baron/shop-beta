-- VELTO-MART Global Trade module, phase 1: database foundation.
-- Existing tables (orders, products, stock, payments) are NOT changed. Trade data lives in new tables that point at them.
-- Money columns are NUMERIC and always sit next to a currency code. Timestamps are unix seconds (BIGINT) like the rest of the schema.
-- Nothing here contains made-up rates, quotes or tracking data: duty rules and carrier rates start EMPTY and are entered or fetched later.

/* ---------- reference data: countries, currencies, exchange rates ---------- */
CREATE TABLE trade_currencies (
  code TEXT PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$'), name TEXT NOT NULL, symbol TEXT NOT NULL DEFAULT '',
  decimals INTEGER NOT NULL DEFAULT 2 CHECK (decimals BETWEEN 0 AND 4),
  is_base INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 0, sort INTEGER NOT NULL DEFAULT 100
);
CREATE UNIQUE INDEX uq_trade_currency_base ON trade_currencies(is_base) WHERE is_base = 1;

CREATE TABLE trade_countries (
  code TEXT PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'), name TEXT NOT NULL, iso3 TEXT NOT NULL DEFAULT '', dial_code TEXT NOT NULL DEFAULT '',
  currency_code TEXT REFERENCES trade_currencies(code), region TEXT NOT NULL DEFAULT '',
  export_to INTEGER NOT NULL DEFAULT 0,       -- customers in this country may be shipped to
  export_from INTEGER NOT NULL DEFAULT 0,     -- we may ship out of this country (origin)
  import_from INTEGER NOT NULL DEFAULT 0,     -- we may buy from suppliers in this country
  import_to INTEGER NOT NULL DEFAULT 0,       -- we may import goods into this country
  tax_id_required INTEGER NOT NULL DEFAULT 0, tax_id_label TEXT NOT NULL DEFAULT '', vat_label TEXT NOT NULL DEFAULT 'VAT',
  postal_required INTEGER NOT NULL DEFAULT 1, postal_regex TEXT NOT NULL DEFAULT '',
  default_incoterm TEXT NOT NULL DEFAULT '', duty_arrangement TEXT NOT NULL DEFAULT 'DAP' CHECK (duty_arrangement IN ('DAP','DDP')),
  config JSONB NOT NULL DEFAULT '{}'::jsonb,  -- anything else that is specific to one country
  active INTEGER NOT NULL DEFAULT 1, sort INTEGER NOT NULL DEFAULT 1000
);
CREATE INDEX idx_trade_countries_export ON trade_countries(export_to, name) WHERE export_to = 1;

CREATE TABLE trade_exchange_rates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, base TEXT NOT NULL REFERENCES trade_currencies(code), quote TEXT NOT NULL REFERENCES trade_currencies(code),
  rate NUMERIC(28,12) NOT NULL CHECK (rate > 0),   -- 1 base = rate quote
  source TEXT NOT NULL, fetched_at BIGINT NOT NULL, provider_updated BIGINT, manual INTEGER NOT NULL DEFAULT 0,
  UNIQUE (base, quote, fetched_at)
);
CREATE INDEX idx_trade_rates_pair ON trade_exchange_rates(base, quote, fetched_at DESC);

CREATE TABLE trade_settings (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '', updated BIGINT NOT NULL DEFAULT 0, updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL);

/* ---------- products ---------- */
CREATE TABLE product_trade_settings (
  product_id BIGINT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
  export_enabled INTEGER NOT NULL DEFAULT 0, import_enabled INTEGER NOT NULL DEFAULT 0, intl_eligible INTEGER NOT NULL DEFAULT 0,
  origin_country TEXT REFERENCES trade_countries(code), hs_code TEXT NOT NULL DEFAULT '' CHECK (hs_code ~ '^([0-9]{4,10}(\.[0-9]+)*)?$'),
  customs_description TEXT NOT NULL DEFAULT '', export_declared_value NUMERIC(18,4) CHECK (export_declared_value IS NULL OR export_declared_value >= 0),
  declared_currency TEXT NOT NULL DEFAULT 'NGN' REFERENCES trade_currencies(code),
  weight_kg NUMERIC(10,3) CHECK (weight_kg IS NULL OR weight_kg >= 0), length_cm NUMERIC(10,2) CHECK (length_cm IS NULL OR length_cm >= 0),
  width_cm NUMERIC(10,2) CHECK (width_cm IS NULL OR width_cm >= 0), height_cm NUMERIC(10,2) CHECK (height_cm IS NULL OR height_cm >= 0),
  shipping_category TEXT NOT NULL DEFAULT 'general', fragile INTEGER NOT NULL DEFAULT 0,
  dangerous_goods INTEGER NOT NULL DEFAULT 0, dangerous_class TEXT NOT NULL DEFAULT '', temperature_controlled INTEGER NOT NULL DEFAULT 0,
  export_restrictions TEXT NOT NULL DEFAULT '', import_restrictions TEXT NOT NULL DEFAULT '',   -- free-text notes; the enforced list is in product_trade_restrictions
  updated BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_pts_export ON product_trade_settings(product_id) WHERE export_enabled = 1 AND intl_eligible = 1;
CREATE INDEX idx_pts_hs ON product_trade_settings(hs_code) WHERE hs_code <> '';

-- A product listed here is NEVER offered for that direction and country.
CREATE TABLE product_trade_restrictions (
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE, country_code TEXT NOT NULL REFERENCES trade_countries(code),
  direction TEXT NOT NULL CHECK (direction IN ('export','import')), reason TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (product_id, country_code, direction)
);
CREATE INDEX idx_ptr_country ON product_trade_restrictions(country_code, direction);

/* ---------- suppliers and procurement ---------- */
CREATE TABLE international_suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, country_code TEXT NOT NULL REFERENCES trade_countries(code),
  address TEXT NOT NULL DEFAULT '', contact_person TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '', website TEXT NOT NULL DEFAULT '',
  currency TEXT NOT NULL DEFAULT 'USD' REFERENCES trade_currencies(code), payment_terms TEXT NOT NULL DEFAULT '', shipping_terms TEXT NOT NULL DEFAULT '', incoterm TEXT NOT NULL DEFAULT '',
  bank_details_enc TEXT NOT NULL DEFAULT '',        -- encrypted; only people with Finance edit rights may read it
  rating NUMERIC(2,1) CHECK (rating IS NULL OR rating BETWEEN 0 AND 5), status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','blocked')),
  notes TEXT NOT NULL DEFAULT '', portal_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,   -- a supplier login, if one is ever created: sees only rows assigned to it
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_isup_country ON international_suppliers(country_code, name);
CREATE UNIQUE INDEX uq_isup_name_country ON international_suppliers(lower(name), country_code);

CREATE TABLE supplier_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id BIGINT NOT NULL REFERENCES international_suppliers(id) ON DELETE CASCADE,
  supplier_sku TEXT NOT NULL DEFAULT '', name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', hs_code TEXT NOT NULL DEFAULT '',
  unit_cost NUMERIC(18,4) NOT NULL CHECK (unit_cost >= 0), currency TEXT NOT NULL REFERENCES trade_currencies(code), moq INTEGER NOT NULL DEFAULT 1 CHECK (moq >= 1),
  lead_time_days INTEGER NOT NULL DEFAULT 0, product_id BIGINT REFERENCES products(id) ON DELETE SET NULL, active INTEGER NOT NULL DEFAULT 1, updated BIGINT NOT NULL
);
CREATE INDEX idx_sprod_supplier ON supplier_products(supplier_id, active);
CREATE INDEX idx_sprod_product ON supplier_products(product_id) WHERE product_id IS NOT NULL;

CREATE TABLE import_purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, po_number TEXT NOT NULL UNIQUE, supplier_id BIGINT NOT NULL REFERENCES international_suppliers(id),
  destination_country TEXT NOT NULL REFERENCES trade_countries(code), currency TEXT NOT NULL REFERENCES trade_currencies(code), incoterm TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','quotation_requested','approved','cancelled')),
  expected_dispatch DATE, expected_arrival DATE, total NUMERIC(18,4) NOT NULL DEFAULT 0, notes TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL, approved_at BIGINT, created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_ipo_supplier ON import_purchase_orders(supplier_id, id DESC);
CREATE INDEX idx_ipo_status ON import_purchase_orders(status, id DESC);

CREATE TABLE import_purchase_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, po_id BIGINT NOT NULL REFERENCES import_purchase_orders(id) ON DELETE CASCADE,
  supplier_product_id BIGINT REFERENCES supplier_products(id) ON DELETE SET NULL, product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  description TEXT NOT NULL, hs_code TEXT NOT NULL DEFAULT '', qty INTEGER NOT NULL CHECK (qty > 0), unit_cost NUMERIC(18,4) NOT NULL CHECK (unit_cost >= 0)
);
CREATE INDEX idx_ipoi_po ON import_purchase_order_items(po_id);

/* ---------- import shipments ---------- */
CREATE TABLE import_shipments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, import_ref TEXT NOT NULL UNIQUE, po_id BIGINT REFERENCES import_purchase_orders(id) ON DELETE SET NULL,
  supplier_id BIGINT NOT NULL REFERENCES international_suppliers(id), supplier_country TEXT NOT NULL REFERENCES trade_countries(code), destination_country TEXT NOT NULL REFERENCES trade_countries(code),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','quotation_requested','po_approved','supplier_processing','ready_for_collection','dispatched','in_transit',
    'arrived_port','customs_clearance','customs_hold','released','local_transit','delivered_warehouse','stock_received','completed')),
  incoterm TEXT NOT NULL DEFAULT '', currency TEXT NOT NULL REFERENCES trade_currencies(code), fx_rate_to_ngn NUMERIC(28,12),   -- rate frozen when costs were recorded
  purchase_value NUMERIC(18,4) NOT NULL DEFAULT 0, freight NUMERIC(18,4) NOT NULL DEFAULT 0, insurance NUMERIC(18,4) NOT NULL DEFAULT 0, customs_duties NUMERIC(18,4) NOT NULL DEFAULT 0,
  import_taxes NUMERIC(18,4) NOT NULL DEFAULT 0, clearing_fees NUMERIC(18,4) NOT NULL DEFAULT 0, port_charges NUMERIC(18,4) NOT NULL DEFAULT 0, inland_transport NUMERIC(18,4) NOT NULL DEFAULT 0,
  other_charges NUMERIC(18,4) NOT NULL DEFAULT 0,
  landed_cost NUMERIC(18,4) GENERATED ALWAYS AS (purchase_value + freight + insurance + customs_duties + import_taxes + clearing_fees + port_charges + inland_transport + other_charges) STORED,
  carrier TEXT NOT NULL DEFAULT '', tracking_number TEXT NOT NULL DEFAULT '', eta DATE, dispatched_at BIGINT, arrived_at BIGINT, received_at BIGINT, warehouse_id BIGINT,
  stock_posted INTEGER NOT NULL DEFAULT 0,   -- 1 once received goods were added to inventory; blocks a second posting
  notes TEXT NOT NULL DEFAULT '', created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_ish_status ON import_shipments(status, id DESC);
CREATE INDEX idx_ish_supplier ON import_shipments(supplier_id, id DESC);
CREATE INDEX idx_ish_tracking ON import_shipments(tracking_number) WHERE tracking_number <> '';

CREATE TABLE import_shipment_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shipment_id BIGINT NOT NULL REFERENCES import_shipments(id) ON DELETE CASCADE,
  po_item_id BIGINT REFERENCES import_purchase_order_items(id) ON DELETE SET NULL, product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  description TEXT NOT NULL, hs_code TEXT NOT NULL DEFAULT '', qty_ordered INTEGER NOT NULL CHECK (qty_ordered > 0), qty_received INTEGER NOT NULL DEFAULT 0 CHECK (qty_received >= 0),
  qty_damaged INTEGER NOT NULL DEFAULT 0 CHECK (qty_damaged >= 0), unit_cost NUMERIC(18,4) NOT NULL CHECK (unit_cost >= 0), weight_kg NUMERIC(10,3), landed_unit_cost_ngn NUMERIC(18,4)
);
CREATE INDEX idx_isi_shipment ON import_shipment_items(shipment_id);

/* ---------- export orders ---------- */
-- The customer's order itself is a normal row in "orders" (so payments, stock and admin screens keep working, in NGN).
-- export_orders adds what is international about it, including the customer's own currency and the rate used at that moment.
CREATE TABLE export_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT, ref TEXT NOT NULL UNIQUE,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, origin_country TEXT NOT NULL REFERENCES trade_countries(code), destination_country TEXT NOT NULL REFERENCES trade_countries(code),
  ship_name TEXT NOT NULL, ship_email TEXT NOT NULL, ship_phone TEXT NOT NULL, phone_dial_code TEXT NOT NULL DEFAULT '', address_line1 TEXT NOT NULL, address_line2 TEXT NOT NULL DEFAULT '',
  city TEXT NOT NULL, region TEXT NOT NULL DEFAULT '', postal_code TEXT NOT NULL DEFAULT '', tax_id TEXT NOT NULL DEFAULT '', delivery_instructions TEXT NOT NULL DEFAULT '', address_validated INTEGER NOT NULL DEFAULT 0,
  currency TEXT NOT NULL REFERENCES trade_currencies(code), fx_rate_to_ngn NUMERIC(28,12) NOT NULL CHECK (fx_rate_to_ngn > 0), fx_source TEXT NOT NULL DEFAULT '',   -- fixed at checkout, never rewritten
  subtotal NUMERIC(18,4) NOT NULL, shipping NUMERIC(18,4) NOT NULL DEFAULT 0, insurance NUMERIC(18,4) NOT NULL DEFAULT 0, duties NUMERIC(18,4) NOT NULL DEFAULT 0, taxes NUMERIC(18,4) NOT NULL DEFAULT 0,
  other_charges NUMERIC(18,4) NOT NULL DEFAULT 0, total NUMERIC(18,4) NOT NULL,
  shipping_method TEXT NOT NULL DEFAULT '', quote_id BIGINT, quote_source TEXT NOT NULL DEFAULT '' CHECK (quote_source IN ('','api','manual_estimate')),
  duty_arrangement TEXT NOT NULL DEFAULT 'DAP' CHECK (duty_arrangement IN ('DAP','DDP')), duties_collected INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','processing','packed','dispatched','in_transit','customs','out_for_delivery','delivered','cancelled','returned')),
  stock_reserved INTEGER NOT NULL DEFAULT 0, stock_deducted INTEGER NOT NULL DEFAULT 0,   -- guards against double reserve / double deduction
  tracking_number TEXT NOT NULL DEFAULT '', carrier TEXT NOT NULL DEFAULT '', eta DATE, created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_exo_status ON export_orders(status, id DESC);
CREATE INDEX idx_exo_user ON export_orders(user_id, id DESC);
CREATE INDEX idx_exo_country ON export_orders(destination_country, created DESC);
CREATE INDEX idx_exo_tracking ON export_orders(tracking_number) WHERE tracking_number <> '';

CREATE TABLE export_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, export_order_id BIGINT NOT NULL REFERENCES export_orders(id) ON DELETE CASCADE, order_item_id BIGINT REFERENCES order_items(id) ON DELETE SET NULL,
  product_id BIGINT NOT NULL, description TEXT NOT NULL, customs_description TEXT NOT NULL DEFAULT '', hs_code TEXT NOT NULL DEFAULT '', origin_country TEXT REFERENCES trade_countries(code),
  qty INTEGER NOT NULL CHECK (qty > 0), unit_price NUMERIC(18,4) NOT NULL, declared_value NUMERIC(18,4) NOT NULL DEFAULT 0, weight_kg NUMERIC(10,3), packed_qty INTEGER NOT NULL DEFAULT 0 CHECK (packed_qty >= 0)
);
CREATE INDEX idx_exoi_order ON export_order_items(export_order_id);

/* ---------- carriers, services, zones, rates ---------- */
-- API keys are NEVER stored here. "credential_env" lists the names of environment variables the server reads; the page only shows whether they are set.
CREATE TABLE shipping_providers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_]+$'), name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'carrier' CHECK (kind IN ('carrier','aggregator','forwarder','air_cargo','sea_freight','manual')),
  adapter TEXT NOT NULL DEFAULT 'manual', credential_env TEXT NOT NULL DEFAULT '[]', enabled INTEGER NOT NULL DEFAULT 0, preferred INTEGER NOT NULL DEFAULT 0, priority INTEGER NOT NULL DEFAULT 100,
  capabilities JSONB NOT NULL DEFAULT '{}'::jsonb, supported_origins TEXT NOT NULL DEFAULT '[]', supported_countries TEXT NOT NULL DEFAULT '[]', sandbox INTEGER NOT NULL DEFAULT 1,
  settings JSONB NOT NULL DEFAULT '{}'::jsonb, created BIGINT NOT NULL, updated BIGINT NOT NULL
);

CREATE TABLE shipping_services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, provider_id BIGINT NOT NULL REFERENCES shipping_providers(id) ON DELETE CASCADE, code TEXT NOT NULL, name TEXT NOT NULL,
  method TEXT NOT NULL CHECK (method IN ('express','standard','economy','air_freight','sea_freight','consolidated','customer_arranged')),
  est_days_min INTEGER, est_days_max INTEGER, supports_ddp INTEGER NOT NULL DEFAULT 0, supports_insurance INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, UNIQUE (provider_id, code)
);

CREATE TABLE shipping_zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE, origin_country TEXT NOT NULL DEFAULT 'NG' REFERENCES trade_countries(code),
  countries TEXT NOT NULL DEFAULT '[]', remote_area_postcodes TEXT NOT NULL DEFAULT '[]', active INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL
);

-- Manually configured estimates. They are always labelled "manual estimate" to customers; they are never shown as live carrier prices.
CREATE TABLE shipping_rate_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, zone_id BIGINT NOT NULL REFERENCES shipping_zones(id) ON DELETE CASCADE, service_id BIGINT REFERENCES shipping_services(id) ON DELETE CASCADE,
  min_kg NUMERIC(10,3) NOT NULL DEFAULT 0, max_kg NUMERIC(10,3), base_amount NUMERIC(18,4) NOT NULL DEFAULT 0, per_kg NUMERIC(18,4) NOT NULL DEFAULT 0, currency TEXT NOT NULL REFERENCES trade_currencies(code),
  fuel_surcharge_pct NUMERIC(7,3) NOT NULL DEFAULT 0, remote_surcharge NUMERIC(18,4) NOT NULL DEFAULT 0, handling_fee NUMERIC(18,4) NOT NULL DEFAULT 0, margin_pct NUMERIC(7,3) NOT NULL DEFAULT 0,
  volumetric_divisor INTEGER NOT NULL DEFAULT 5000 CHECK (volumetric_divisor > 0), active INTEGER NOT NULL DEFAULT 1, updated BIGINT NOT NULL,
  CHECK (max_kg IS NULL OR max_kg > min_kg)
);
CREATE INDEX idx_srr_zone ON shipping_rate_rules(zone_id, active);

CREATE TABLE shipping_rate_quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cart_key TEXT NOT NULL DEFAULT '', user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  provider_id BIGINT REFERENCES shipping_providers(id) ON DELETE SET NULL, service_id BIGINT REFERENCES shipping_services(id) ON DELETE SET NULL, service_label TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL CHECK (source IN ('api','manual_estimate')), origin_country TEXT NOT NULL, destination_country TEXT NOT NULL,
  currency TEXT NOT NULL REFERENCES trade_currencies(code), amount NUMERIC(18,4) NOT NULL, insurance NUMERIC(18,4) NOT NULL DEFAULT 0, duties NUMERIC(18,4), taxes NUMERIC(18,4),
  actual_kg NUMERIC(10,3), volumetric_kg NUMERIC(10,3), chargeable_kg NUMERIC(10,3), est_days_min INTEGER, est_days_max INTEGER,
  breakdown JSONB NOT NULL DEFAULT '{}'::jsonb, provider_quote_ref TEXT NOT NULL DEFAULT '', expires_at BIGINT NOT NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_srq_cart ON shipping_rate_quotes(cart_key, created DESC);
CREATE INDEX idx_srq_expires ON shipping_rate_quotes(expires_at);

/* ---------- bookings, labels, tracking ---------- */
CREATE TABLE shipping_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, export_order_id BIGINT REFERENCES export_orders(id) ON DELETE RESTRICT, import_shipment_id BIGINT REFERENCES import_shipments(id) ON DELETE RESTRICT,
  provider_id BIGINT NOT NULL REFERENCES shipping_providers(id), service_id BIGINT REFERENCES shipping_services(id),
  idempotency_key TEXT NOT NULL UNIQUE,   -- one booking per key: a retry returns the first result and never books twice
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','booked','failed','cancel_requested','cancelled')),
  provider_ref TEXT NOT NULL DEFAULT '', tracking_number TEXT NOT NULL DEFAULT '', awb_number TEXT NOT NULL DEFAULT '', pickup_at BIGINT, cost NUMERIC(18,4), currency TEXT REFERENCES trade_currencies(code),
  insured INTEGER NOT NULL DEFAULT 0, error TEXT NOT NULL DEFAULT '', request_summary JSONB NOT NULL DEFAULT '{}'::jsonb, booked_at BIGINT, created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created BIGINT NOT NULL, updated BIGINT NOT NULL,
  CHECK ((export_order_id IS NOT NULL) <> (import_shipment_id IS NOT NULL)),
  CHECK (status NOT IN ('booked') OR provider_ref <> '')   -- never "booked" without the carrier's own confirmation reference
);
CREATE INDEX idx_sbk_export ON shipping_bookings(export_order_id);
CREATE INDEX idx_sbk_import ON shipping_bookings(import_shipment_id);
CREATE INDEX idx_sbk_tracking ON shipping_bookings(tracking_number) WHERE tracking_number <> '';
CREATE UNIQUE INDEX uq_sbk_one_active_export ON shipping_bookings(export_order_id) WHERE export_order_id IS NOT NULL AND status IN ('requested','booked');

CREATE TABLE shipping_labels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL REFERENCES shipping_bookings(id) ON DELETE CASCADE, kind TEXT NOT NULL DEFAULT 'label' CHECK (kind IN ('label','waybill','awb')),
  format TEXT NOT NULL DEFAULT 'pdf', storage_path TEXT NOT NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_slb_booking ON shipping_labels(booking_id);

CREATE TABLE shipment_tracking_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, export_order_id BIGINT REFERENCES export_orders(id) ON DELETE CASCADE, import_shipment_id BIGINT REFERENCES import_shipments(id) ON DELETE CASCADE,
  booking_id BIGINT REFERENCES shipping_bookings(id) ON DELETE SET NULL,
  stage TEXT NOT NULL CHECK (stage IN ('order_confirmed','processing','packed','dispatched','export_customs','departed_origin','in_transit','arrived_destination','import_customs','customs_released','out_for_delivery','delivered','delayed','exception','customs_hold')),
  description TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT '', occurred_at BIGINT NOT NULL, source TEXT NOT NULL CHECK (source IN ('api','webhook','manual','system')),
  event_hash TEXT NOT NULL UNIQUE,   -- hash of provider + code + time + place, so a repeated webhook or poll adds nothing
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created BIGINT NOT NULL,
  CHECK ((export_order_id IS NOT NULL) <> (import_shipment_id IS NOT NULL))
);
CREATE INDEX idx_ste_export ON shipment_tracking_events(export_order_id, occurred_at);
CREATE INDEX idx_ste_import ON shipment_tracking_events(import_shipment_id, occurred_at);

/* ---------- customs and documents ---------- */
CREATE TABLE customs_declarations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref TEXT NOT NULL UNIQUE, export_order_id BIGINT REFERENCES export_orders(id) ON DELETE CASCADE, import_shipment_id BIGINT REFERENCES import_shipments(id) ON DELETE CASCADE,
  direction TEXT NOT NULL CHECK (direction IN ('export','import')), export_country TEXT NOT NULL REFERENCES trade_countries(code), import_country TEXT NOT NULL REFERENCES trade_countries(code),
  incoterm TEXT NOT NULL DEFAULT '', declared_value NUMERIC(18,4) NOT NULL DEFAULT 0, currency TEXT NOT NULL REFERENCES trade_currencies(code),
  gross_weight_kg NUMERIC(10,3), net_weight_kg NUMERIC(10,3), packages INTEGER, dimensions TEXT NOT NULL DEFAULT '', restrictions_note TEXT NOT NULL DEFAULT '',
  lines JSONB NOT NULL DEFAULT '[]'::jsonb,   -- per line: HS code, description, origin, qty, value
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','incomplete','ready','submitted','cleared','held','rejected')),
  reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL, reviewed_at BIGINT, created BIGINT NOT NULL, updated BIGINT NOT NULL,
  CHECK ((export_order_id IS NOT NULL) <> (import_shipment_id IS NOT NULL))
);
CREATE INDEX idx_cd_status ON customs_declarations(status, id DESC);

CREATE TABLE trade_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, doc_type TEXT NOT NULL CHECK (doc_type IN ('commercial_invoice','proforma_invoice','packing_list','certificate_of_origin','export_declaration','shipping_label',
    'air_waybill','bill_of_lading','customs_declaration','insurance_certificate','import_permit','supplier_invoice','purchase_agreement','goods_received_note','picking_list','other')),
  number TEXT NOT NULL DEFAULT '', export_order_id BIGINT REFERENCES export_orders(id) ON DELETE CASCADE, import_shipment_id BIGINT REFERENCES import_shipments(id) ON DELETE CASCADE,
  po_id BIGINT REFERENCES import_purchase_orders(id) ON DELETE CASCADE, supplier_id BIGINT REFERENCES international_suppliers(id) ON DELETE CASCADE,
  origin TEXT NOT NULL DEFAULT 'generated' CHECK (origin IN ('generated','uploaded')), file_name TEXT NOT NULL DEFAULT '', storage_path TEXT NOT NULL DEFAULT '', mime TEXT NOT NULL DEFAULT 'application/pdf', size_bytes BIGINT NOT NULL DEFAULT 0,
  data JSONB NOT NULL DEFAULT '{}'::jsonb, version INTEGER NOT NULL DEFAULT 1, status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','issued','void')),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL, created BIGINT NOT NULL
);
CREATE INDEX idx_td_export ON trade_documents(export_order_id, doc_type);
CREATE INDEX idx_td_import ON trade_documents(import_shipment_id, doc_type);

CREATE TABLE customs_documents (
  declaration_id BIGINT NOT NULL REFERENCES customs_declarations(id) ON DELETE CASCADE, document_id BIGINT NOT NULL REFERENCES trade_documents(id) ON DELETE CASCADE, required INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (declaration_id, document_id)
);

-- Duty and tax rules are entered by staff (or imported from a verified source). Nothing is pre-filled. An unverified rule produces only an ESTIMATE.
CREATE TABLE customs_duty_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, destination_country TEXT NOT NULL REFERENCES trade_countries(code), origin_country TEXT REFERENCES trade_countries(code),
  hs_prefix TEXT NOT NULL DEFAULT '' CHECK (hs_prefix ~ '^[0-9]*$'), duty_pct NUMERIC(7,3) NOT NULL DEFAULT 0 CHECK (duty_pct >= 0), vat_pct NUMERIC(7,3) NOT NULL DEFAULT 0 CHECK (vat_pct >= 0),
  other_levy_pct NUMERIC(7,3) NOT NULL DEFAULT 0 CHECK (other_levy_pct >= 0), other_levy_label TEXT NOT NULL DEFAULT '',
  valuation TEXT NOT NULL DEFAULT 'CIF' CHECK (valuation IN ('FOB','CIF','CIP')), vat_on_duty INTEGER NOT NULL DEFAULT 1,   -- VAT base includes duty (common, but set per country)
  de_minimis NUMERIC(18,4), de_minimis_currency TEXT REFERENCES trade_currencies(code),
  source TEXT NOT NULL DEFAULT '', source_url TEXT NOT NULL DEFAULT '', verified INTEGER NOT NULL DEFAULT 0, verified_by BIGINT REFERENCES users(id) ON DELETE SET NULL, verified_at BIGINT,
  valid_from DATE, valid_to DATE, notes TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1, created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_cdr_lookup ON customs_duty_rules(destination_country, hs_prefix, active);

/* ---------- payments ---------- */
CREATE TABLE international_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, export_order_id BIGINT NOT NULL REFERENCES export_orders(id) ON DELETE RESTRICT, order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
  provider TEXT NOT NULL CHECK (provider IN ('paystack','flutterwave','stripe','other')), provider_ref TEXT NOT NULL, currency TEXT NOT NULL REFERENCES trade_currencies(code),
  amount NUMERIC(18,4) NOT NULL CHECK (amount >= 0), fee NUMERIC(18,4) NOT NULL DEFAULT 0, fx_rate_to_ngn NUMERIC(28,12), amount_ngn NUMERIC(18,4),
  kind TEXT NOT NULL DEFAULT 'charge' CHECK (kind IN ('charge','refund')), status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','succeeded','failed','refunded','partially_refunded')),
  verified INTEGER NOT NULL DEFAULT 0, verified_at BIGINT, parent_id BIGINT REFERENCES international_payments(id), created BIGINT NOT NULL, updated BIGINT NOT NULL,
  UNIQUE (provider, provider_ref),
  CHECK (status NOT IN ('succeeded') OR verified = 1)   -- "paid" only after the provider's own confirmation was checked server-side
);
