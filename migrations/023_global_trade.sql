/* ---------- row level security ----------
   VELTO-MART signs people in with its own sessions, not Supabase Auth, so there is no auth.uid() for a policy to compare against.
   The safe equivalent is used here, the same as every other table: RLS is ON with NO policies, so the Supabase public (anon / authenticated)
   keys can read and write nothing. All access goes through the server, which checks the session first:
     customers  -> only their own export orders, payments and tracking (WHERE user_id = the signed-in user, or order ref + access token);
     suppliers  -> only rows assigned to them (WHERE supplier_id / portal_user_id = the signed-in supplier);
     staff      -> only through /api/admin/trade, gated by the "trade" role module (see lib/staff.js).
   test/trade.js checks that every trade table has RLS on and no policies. */
DO $$
DECLARE t TEXT;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND (tablename LIKE 'trade\_%' OR tablename LIKE 'shipping\_%' OR tablename LIKE 'customs\_%' OR tablename LIKE 'import\_%' OR tablename LIKE 'export\_%'
      OR tablename IN ('product_trade_settings','product_trade_restrictions','international_suppliers','supplier_products','shipment_tracking_events','international_payments','landed_cost_allocations'))
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
