-- Public Import & Export enquiries: people who want goods brought in from abroad (import) or want to buy Nigerian goods to ship out (export).
CREATE TABLE IF NOT EXISTS trade_enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL CHECK (kind IN ('import','export')),
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','in_progress','quoted','won','lost','spam')),
  name TEXT NOT NULL, company TEXT NOT NULL DEFAULT '', email TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '',
  country TEXT NOT NULL DEFAULT '',             -- import: where the goods are coming from; export: where they are going
  item TEXT NOT NULL, quantity TEXT NOT NULL DEFAULT '', budget TEXT NOT NULL DEFAULT '', timeline TEXT NOT NULL DEFAULT '',
  shipping TEXT NOT NULL DEFAULT '',            -- air | sea | any
  details TEXT NOT NULL DEFAULT '',
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  note TEXT NOT NULL DEFAULT '', handled_by TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL, contacted_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_trade_enquiries_status ON trade_enquiries(status, id DESC);
CREATE INDEX IF NOT EXISTS idx_trade_enquiries_email ON trade_enquiries(email, created DESC);
ALTER TABLE trade_enquiries ENABLE ROW LEVEL SECURITY;
