-- Wholesale orders: order numbers, final invoices, picking / packing, dispatch and delivery proof.
-- Quote statuses are unchanged (paid -> shipped -> delivered). Between "paid" and "shipped" the warehouse works through fulfilment stages:
--   to_pick -> picking -> picked -> packed -> dispatched -> delivered

ALTER TABLE wholesale_quotes ADD COLUMN order_no TEXT, ADD COLUMN invoice_no TEXT;
CREATE UNIQUE INDEX uq_wholesale_quotes_order_no ON wholesale_quotes(order_no) WHERE order_no IS NOT NULL;
CREATE UNIQUE INDEX uq_wholesale_quotes_invoice_no ON wholesale_quotes(invoice_no) WHERE invoice_no IS NOT NULL;

-- The final invoice is a frozen copy of what the buyer paid for. It is never edited: a later price change cannot alter it.
CREATE TABLE wholesale_invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_no TEXT NOT NULL UNIQUE,
  quote_id BIGINT NOT NULL UNIQUE REFERENCES wholesale_quotes(id),
  order_no TEXT NOT NULL,
  account_id BIGINT NOT NULL REFERENCES wholesale_accounts(id),
  snapshot TEXT NOT NULL,                                   -- JSON: seller, buyer, delivery address, lines, fees, totals, payment
  total INTEGER NOT NULL,
  issued BIGINT NOT NULL, issued_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_wholesale_invoices_issued ON wholesale_invoices(issued DESC);

CREATE TABLE wholesale_fulfilments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id BIGINT NOT NULL UNIQUE REFERENCES wholesale_quotes(id),
  warehouse_id BIGINT NOT NULL REFERENCES wholesale_warehouses(id),
  stage TEXT NOT NULL DEFAULT 'to_pick' CHECK (stage IN ('to_pick','picking','picked','packed','dispatched','delivered')),
  picker TEXT NOT NULL DEFAULT '', picking_started BIGINT, picked_at BIGINT,
  packer TEXT NOT NULL DEFAULT '', packed_at BIGINT, packages INTEGER NOT NULL DEFAULT 0, package_note TEXT NOT NULL DEFAULT '',
  driver_name TEXT NOT NULL DEFAULT '', driver_phone TEXT NOT NULL DEFAULT '', vehicle_no TEXT NOT NULL DEFAULT '', expected_note TEXT NOT NULL DEFAULT '',
  dispatched_by TEXT NOT NULL DEFAULT '', dispatched_at BIGINT,
  received_by TEXT NOT NULL DEFAULT '', delivery_note TEXT NOT NULL DEFAULT '', delivered_by TEXT NOT NULL DEFAULT '', delivered_at BIGINT,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  created BIGINT NOT NULL, updated BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_fulfilments_stage ON wholesale_fulfilments(stage);

CREATE TABLE wholesale_pick_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fulfilment_id BIGINT NOT NULL REFERENCES wholesale_fulfilments(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  name TEXT NOT NULL, sku TEXT NOT NULL DEFAULT '',
  qty INTEGER NOT NULL CHECK (qty > 0),
  qty_picked INTEGER NOT NULL DEFAULT 0 CHECK (qty_picked >= 0),
  short_note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_wholesale_pick_lines_f ON wholesale_pick_lines(fulfilment_id);

-- Internal trail of the warehouse work (never shown to buyers; buyers see only the shipped / delivered events on the quote).
CREATE TABLE wholesale_fulfilment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fulfilment_id BIGINT NOT NULL REFERENCES wholesale_fulfilments(id) ON DELETE CASCADE,
  stage TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX idx_wholesale_fulfilment_events_f ON wholesale_fulfilment_events(fulfilment_id, id);

ALTER TABLE wholesale_invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_fulfilments ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_pick_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE wholesale_fulfilment_events ENABLE ROW LEVEL SECURITY;
