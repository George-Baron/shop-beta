-- Step 6 of dropshipping: money. What we owe each supplier, extra costs per item, refunds (to customers and from suppliers), returns to the supplier.
-- Safe to run again. Nothing is deleted or rewritten; existing rows only get new columns and (for orders already sent) a payable.

-- The exchange rate used when the supplier cost was fixed (Naira per 1 unit of the supplier's currency).
ALTER TABLE dropship_lines ADD COLUMN IF NOT EXISTS cost_fx_rate NUMERIC(18,8);
UPDATE dropship_lines SET cost_fx_rate = ROUND(cost_ngn::numeric / ((unit_cost + ship_cost) * qty), 8)
 WHERE cost_fx_rate IS NULL AND cost_ngn IS NOT NULL AND (unit_cost + ship_cost) > 0;

-- What we owe a supplier for one purchase order. Created when the order is sent. amount is in the supplier's currency; credit is what the supplier
-- refunded as credit against this order. Net owed = amount - credit.
CREATE TABLE IF NOT EXISTS supplier_payables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_id BIGINT NOT NULL UNIQUE REFERENCES supplier_orders(id) ON DELETE CASCADE,
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  currency CHAR(3) NOT NULL,
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  credit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  due_at BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','paid','void')),
  paid_at BIGINT, paid_amount NUMERIC(14,2), paid_ngn INTEGER, paid_ref TEXT NOT NULL DEFAULT '', paid_by TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payables_supplier ON supplier_payables(supplier_id, status, due_at);
CREATE INDEX IF NOT EXISTS idx_payables_due ON supplier_payables(status, due_at);

-- Payables for purchase orders that were sent before this step existed.
INSERT INTO supplier_payables (po_id, supplier_id, currency, amount, due_at, created)
SELECT so.id, so.supplier_id, so.currency, so.total_cost,
       COALESCE(so.sent_at, so.created) + COALESCE(s.payment_days, 0) * 86400, COALESCE(so.sent_at, so.created)
  FROM supplier_orders so JOIN suppliers s ON s.id = so.supplier_id
 WHERE so.status = 'sent' AND NOT EXISTS (SELECT 1 FROM supplier_payables p WHERE p.po_id = so.id);

-- Costs we pay on an item beyond the supplier price: duty, extra shipping, handling, payment fee actually charged, other. Whole Naira.
CREATE TABLE IF NOT EXISTS dropship_line_costs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL REFERENCES dropship_lines(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('duty','shipping','handling','gateway_fee','other')),
  amount_ngn INTEGER NOT NULL CHECK (amount_ngn >= 0),
  note TEXT NOT NULL DEFAULT '', created_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_line_costs_line ON dropship_line_costs(line_id);

-- Money given back to a customer for an item (whole Naira). Written when the refund is recorded, so reports keep the amount even after refund_due is cleared.
CREATE TABLE IF NOT EXISTS dropship_refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL UNIQUE REFERENCES dropship_lines(id) ON DELETE CASCADE,
  amount_ngn INTEGER NOT NULL CHECK (amount_ngn >= 0),
  reference TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', created_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);

-- Money a supplier gives back to us for an item. mode 'credit' lowers what we owe on that purchase order; 'cash' is money received.
CREATE TABLE IF NOT EXISTS supplier_refunds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL REFERENCES dropship_lines(id) ON DELETE CASCADE,
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  currency CHAR(3) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK (amount > 0), amount_ngn INTEGER NOT NULL DEFAULT 0,
  mode TEXT NOT NULL CHECK (mode IN ('credit','cash')),
  reference TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '', created_by TEXT NOT NULL DEFAULT '', created BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_supplier_refunds_line ON supplier_refunds(line_id);
CREATE INDEX IF NOT EXISTS idx_supplier_refunds_supplier ON supplier_refunds(supplier_id, id DESC);

-- A customer return that goes back to the supplier. The item itself moves delivered -> returned; this tracks the parcel going back and the supplier's answer.
CREATE TABLE IF NOT EXISTS dropship_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL UNIQUE REFERENCES dropship_lines(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','approved','sent_back','received','rejected','closed')),
  reason TEXT NOT NULL DEFAULT '', rma_no TEXT NOT NULL DEFAULT '', carrier TEXT NOT NULL DEFAULT '', tracking_no TEXT NOT NULL DEFAULT '', note TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, updated BIGINT NOT NULL, created_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_returns_status ON dropship_returns(status, id DESC);

