-- Background job queue (emails, order mails, Paystack webhooks, scheduled housekeeping). Works through the Supabase transaction pooler:
-- jobs are claimed with FOR UPDATE SKIP LOCKED inside one statement, and a crashed worker's job comes back when its lease runs out.
CREATE TABLE jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  queue TEXT NOT NULL,
  payload TEXT NOT NULL DEFAULT '{}',
  state TEXT NOT NULL DEFAULT 'queued',          -- queued | active | done | failed
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 6,
  run_at BIGINT NOT NULL,                        -- do not start before this time (unix seconds); used for retry delays
  locked_until BIGINT NOT NULL DEFAULT 0,        -- lease while a worker holds the job
  singleton_key TEXT,                            -- at most one queued/active job per key
  last_error TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL,
  finished BIGINT
);
CREATE INDEX idx_jobs_due ON jobs (run_at, id) WHERE state IN ('queued', 'active');
CREATE INDEX idx_jobs_failed ON jobs (finished DESC) WHERE state = 'failed';
CREATE INDEX idx_jobs_queue_created ON jobs (queue, created DESC);
CREATE UNIQUE INDEX uq_jobs_singleton ON jobs (singleton_key) WHERE singleton_key IS NOT NULL AND state IN ('queued', 'active');
