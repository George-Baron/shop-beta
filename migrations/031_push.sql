-- Push notifications for the mobile apps (Expo). Tokens belong to one signed-in device; they are removed at sign-out and when Expo reports them dead.
CREATE TABLE push_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_id BIGINT REFERENCES mobile_sessions(id) ON DELETE CASCADE,
  token TEXT NOT NULL UNIQUE,
  platform TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL, last_seen BIGINT NOT NULL,
  disabled_at BIGINT, disabled_reason TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_push_tokens_user ON push_tokens(user_id) WHERE disabled_at IS NULL;
-- What each customer wants to hear about. A missing row means the defaults (orders and wholesale on, offers off).
CREATE TABLE push_prefs (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  orders INTEGER NOT NULL DEFAULT 1, wholesale INTEGER NOT NULL DEFAULT 1, offers INTEGER NOT NULL DEFAULT 0,
  updated BIGINT NOT NULL
);
-- One row per notification that was pushed: the unique key is what stops the same event reaching a phone twice.
CREATE TABLE push_deliveries (
  notification_id BIGINT PRIMARY KEY REFERENCES notifications(id) ON DELETE CASCADE,
  sent_at BIGINT NOT NULL, tokens INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE push_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE push_prefs ENABLE ROW LEVEL SECURITY;
ALTER TABLE push_deliveries ENABLE ROW LEVEL SECURITY;
